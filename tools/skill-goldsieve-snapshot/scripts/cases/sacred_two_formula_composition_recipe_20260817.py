"""Аудит воспроизводимости раздела о составных священных формулах.

Раздел сообщает об ускорении после сложения двух формул, но не публикует
сами две формулы, их коэффициенты, единицы и правило подбора. Кейс проверяет
полноту рецепта, а не превращает напечатанные проценты в подтверждение.
"""
import os
import re
import sys

from goldsieve.sieve import Claim

ИСТОЧНИК = (
    "/home/user/workspace/corpus/trinity/docs/docs/math-foundations/"
    "sacred-formulas.md"
)

# Тихий отказ: настоящий загрузчик использует module_from_spec без регистрации.
if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться через module_from_spec без sys.modules")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("источник составных формул отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def _раздел():
    текст = _текст()
    начало = текст.find("### Two-Formula Composition (Acceleration)")
    # Ищем горизонтальный разделитель отдельной строкой, а не строку
    # разметки таблицы ``|-----------|``.
    конец = текст.find("\n---\n", начало)
    if начало < 0 or конец < 0:
        raise AssertionError("раздел составных формул не найден")
    return текст[начало:конец]


def наблюдение():
    """Отдельный табличный маршрут: извлекает три строки и числа ускорения."""
    строки = _раздел().splitlines()
    результаты = []
    for строка in строки:
        части = [часть.strip() for часть in строка.strip().strip("|").split("|")]
        if len(части) == 4 and части[0].startswith("$"):
            совпадение = re.fullmatch(r"\*\*([0-9]+(?:\.[0-9]+)?)×\*\*", части[3])
            if not совпадение:
                raise AssertionError("ускорение в строке таблицы не найдено")
            результаты.append({
                "цель": re.sub(r"\$", "", части[0]),
                "исходная_ошибка": части[1],
                "составная_ошибка": части[2],
                "ускорение": float(совпадение.group(1)),
            })
    if len(результаты) != 3:
        raise AssertionError("ожидались три строки составной таблицы")
    return результаты


def _инвентарь():
    """Вычислить наличие полей рецепта по всему исходному документу."""
    текст = _текст().lower()
    раздел = _раздел().lower()
    поля = {
        "три строки таблицы": len(наблюдение()) == 3,
        "два исходных выражения для каждой цели": bool(
            re.search(r"v_1|v1|formula\s*1", раздел)
        ),
        "правило сложения": bool(re.search(r"v_1\s*\+\s*v_2|v1\s*\+\s*v2", раздел)),
        "единицы и нормировка": bool(re.search(r"unit|нормир", раздел)),
        "исходные данные и разбиение": bool(
            re.search(r"raw data|dataset|split|разбиен", текст)
        ),
        "независимый повтор": bool(re.search(r"independent repeat|replicat", текст)),
    }
    поля["рецепт_полон"] = all(поля.values())
    поля["отсутствует"] = [
        имя for имя, есть in поля.items()
        if имя not in {"рецепт_полон", "отсутствует"} and not есть
    ]
    return поля


def эталон():
    """Независимый маршрут: проверяет обязательные поля рецепта."""
    инвентарь = _инвентарь()
    return 1.0 if инвентарь["рецепт_полон"] else 0.0


def эталон_альт():
    """Второй метод: построчный поиск маркеров и подсчёт строк таблицы."""
    строки = _раздел().splitlines()
    таблица = [строка for строка in строки if строка.count("|") == 4]
    маркеры = "\n".join(строки).lower()
    обязательные = {
        "два_выражения": bool(re.search(r"v_1|v1|formula\s*1", маркеры)),
        "правило": bool(re.search(r"v_1\s*\+\s*v_2|v1\s*\+\s*v2", маркеры)),
        "единицы": bool(re.search(r"unit|нормир", маркеры)),
    }
    return 1.0 if len(таблица) == 3 and all(обязательные.values()) else 0.0


def наблюдаемое_состояние():
    """Наблюдение отдельным путём: таблица и её маркеры, не эталон."""
    строки = наблюдение()
    текст = _раздел().lower()
    есть_маркеры = all(
        re.search(шаблон, текст)
        for шаблон in (r"v_1|v1|formula\s*1",
                       r"v_1\s*\+\s*v_2|v1\s*\+\s*v2",
                       r"unit|нормир")
    )
    return 1.0 if len(строки) == 3 and есть_маркеры else 0.0


def _неверная_подстановка():
    return 1.0


def _контроль():
    return 1.0


def _код_причины():
    return "" if эталон() == 1.0 else "metrics_incommensurable"


def _самопроверка():
    наблюдаемое = наблюдение()
    assert len(наблюдаемое) == 3
    assert наблюдаемое[0]["ускорение"] == 3905.0
    assert наблюдаемое[1]["ускорение"] == 1610.0
    assert наблюдаемое[2]["ускорение"] == 121.0
    эт = эталон()
    алт = эталон_альт()
    assert эт == 0.0
    assert алт == 0.0
    assert наблюдаемое_состояние() == 0.0
    assert _неверная_подстановка() != эт
    assert _контроль() != эт
    assert _код_причины() == "metrics_incommensurable"


_самопроверка()


