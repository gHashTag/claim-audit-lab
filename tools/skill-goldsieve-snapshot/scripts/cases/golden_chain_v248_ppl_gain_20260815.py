from goldsieve.sieve import Claim


ОТЧЁТ = os.environ.get(
    "TRINITY_GOLDEN_CHAIN_V248_REPORT",
    "/home/user/workspace/corpus/trinity/docs/docs/research/"
    "trinity-golden-chain-v2-48-interpolated-report.md",
)


def _текст():
    """Защита от тихого отказа: проверяется реальный вход текущего вызова."""
    if not os.path.isfile(ОТЧЁТ):
        raise AssertionError("отчёт v2.48 недоступен: " + ОТЧЁТ)
    with open(ОТЧЁТ, encoding="utf-8") as файл:
        текст = файл.read()
    if "Interp improvement:" not in текст or "Interpolated Eval PPL" not in текст:
        raise AssertionError("в отчёте нет двух обязательных блоков")
    return текст


def _наблюдение():
    """Наблюдение читается только из контрольного запуска Test 43."""
    совпадение = re.search(
        r"Interp improvement:\s*([-0-9.]+)%\s+below bigram",
        _текст(),
    )
    if not совпадение:
        raise AssertionError("строка наблюдаемого выигрыша не найдена")
    return float(совпадение.group(1))


def _значения_эталона():
    """Извлечь две PPL из таблицы показателей, не читая строку выигрыша."""
    совпадение = re.search(
        r"\|\s*Interpolated Eval PPL\s*\|\s*\*\*([0-9.]+)\*\*"
        r"\s*\|\s*Was\s+[0-9.]+\s+\(tri\)\s*/\s*([0-9.]+)\s+\(bi\)\s*\|",
        _текст(),
    )
    if not совпадение:
        raise AssertionError("табличные PPL для эталона не найдены")
    return float(совпадение.group(1)), float(совпадение.group(2))


def _эталон():
    """Вычислимый эталон: относительное снижение PPL против чистого биграммного метода."""
    интерполированная, биграммная = _значения_эталона()
    return 100.0 * (биграммная - интерполированная) / биграммная


def _эталон_альт():
    """Независимый путь: Decimal из блока контрольного запуска Test 43."""
    совпадения = re.findall(
        r"^\s*(?:Interpolated: train=[0-9.]+\s+eval=([0-9.]+)\s+gap=[0-9.]+"
        r"|Pure bigram eval:\s*([0-9.]+))\s*$",
        _текст(),
        re.MULTILINE,
    )
    интерполированные = [а for а, _ in совпадения if а]
    биграммные = [б for _, б in совпадения if б]
    if len(интерполированные) != 1 or len(биграммные) != 1:
        raise AssertionError("контрольный блок Test 43 изменился")
    with localcontext() as контекст:
        контекст.prec = 40
        интерполированная = Decimal(интерполированные[0])
        биграммная = Decimal(биграммные[0])
        return float(Decimal(100) * (биграммная - интерполированная) / биграммная)


def _подставка():
    """Намеренно неверный выигрыш."""
    return 7.0


def _отрицательный_контроль():
    """Отсутствие выигрыша — отличающийся режим."""
    return 0.0


def _самопроверка():
    assert _наблюдение() == 3.9
    assert abs(_эталон() - 3.8746630727762756) < 1.0e-12
    assert abs(_эталон_альт() - _эталон()) < 1.0e-12
    assert abs(_наблюдение() - _эталон()) < 0.1
    assert _подставка() != _эталон()
    assert _отрицательный_контроль() != _эталон()


_самопроверка()


