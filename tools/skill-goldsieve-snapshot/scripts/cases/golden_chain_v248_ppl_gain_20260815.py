"""Аудит заявления о выигрыше интерполяции по перплексии.

Наблюдение извлекается из отдельной строки отчёта о контрольном запуске.
Эталон получает две величины перплексии из таблицы показателей и вычисляет
относительное снижение. Альтернативный эталон использует Decimal и другой
маркер текста; напечатанное «3,9 %» в эталоны не передаётся.
"""

import os
import re
