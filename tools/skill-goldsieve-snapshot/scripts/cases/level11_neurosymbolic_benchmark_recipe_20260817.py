"""Проверка воспроизводимости нейросимвольного benchmark Level 11.31.

Наблюдение берётся из строки сводки. Эталон выводится из трёх отдельных
строк Test 145/146/147. Альтернативный эталон читает ту же таблицу отдельным
табличным разбором. Это проверка нового источника и риска рецепта benchmark,
а не дешёвое подтверждение отношения двух напечатанных чисел: без сырых
запросов, ответов и версии реализации результат остаётся ВОПРОСОМ.
"""
import csv
import os
import re
import sys

from goldsieve.sieve import Claim

ИСТОЧНИК = (
    "/home/user/workspace/corpus/trinity/docs/docs/research/"
    "trinity-level11-neuro-symbolic-bench-report.md"
)

if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться через module_from_spec без регистрации в sys.modules")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Level 11.31 отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def наблюдение():
    """Извлечь агрегат из отдельной строки сводки отчёта."""
    совпадение = re.search(
        r"166 queries,\s*(\d+) correct\s*\((\d+(?:\.\d+)?)%\)",
        _текст(),
        re.I,
    )
    if not совпадение:
        raise AssertionError("агрегат 166 запросов не найден")
    правильные, процент = совпадение.groups()
    return {"правильные": float(правильные), "запросы": 166.0, "процент": float(процент)}


def _строки_компонентов():
    """Извлечь три компонента из таблицы Key Metrics отдельным regex-путём."""
    строки = []
    for номер in (145, 146, 147):
        совпадение = re.search(
            rf"\|\s*Test {номер}\s*\|[^|]+\|\s*(\d+)/(\d+)\s*\([^|]+\)\s*\|",
            _текст(),
        )
        if not совпадение:
            raise AssertionError(f"строка Test {номер} не найдена")
        строки.append(tuple(map(int, совпадение.groups())))
    return строки


def эталон():
    """Вычислить агрегат суммированием трёх компонент benchmark."""
    компоненты = _строки_компонентов()
    правильные = sum(п for п, _ in компоненты)
    запросы = sum(в for _, в in компоненты)
    return {"правильные": float(правильные), "запросы": float(запросы),
            "процент": float(100.0 * правильные / запросы)}


def эталон_альт():
    """Альтернативный путь: CSV-разбор таблицы Key Metrics и Decimal-подобное суммирование."""
    найдено = []
    в_таблице = False
    for строка in _текст().splitlines():
        if строка.strip() == "| Test | Description | Result | Status |":
            в_таблице = True
            continue
        if not в_таблице:
            continue
        if not строка.startswith("|"):
            if найдено:
                break
            continue
        поля = next(csv.reader([строка], delimiter="|"))
        ячейки = [поле.strip() for поле in поля]
        if len(ячейки) < 4:
            continue
        if ячейки[1] in {"Test 145", "Test 146", "Test 147"}:
            совпадение = re.fullmatch(r"(\d+)/(\d+)\s*\([^)]*\)", ячейки[3])
            if совпадение:
                найдено.append(tuple(int(x) for x in совпадение.groups()))
    if len(найдено) != 3:
        raise AssertionError("альтернативный табличный разбор не нашёл три компонента")
    правильные = sum(п for п, _ in найдено)
    запросы = sum(в for _, в in найдено)
    return {"правильные": float(правильные), "запросы": float(запросы),
            "процент": float(100.0 * правильные / запросы)}


def _контроль_полной_регрессии():
    """Отдельный контроль: полная регрессия проекта, не benchmark Level 11.31."""
    совпадение = re.search(r"Full Regression\s*\|\s*All (\d+) tests\s*\|\s*(\d+) pass,\s*(\d+) skip,\s*(\d+) fail", _текст())
    if not совпадение:
        raise AssertionError("строка полной регрессии не найдена")
    всего, pass_, skip, fail = map(int, совпадение.groups())
    return {"правильные": float(pass_), "запросы": float(всего), "процент": float(100.0 * pass_ / всего), "пропуски": float(skip), "ошибки": float(fail)}


def _неверная_подстановка():
    return {"правильные": 161.0, "запросы": 166.0, "процент": 96.98795180722891}


def _рецепт_полон():
    """Инвентаризация обязательных частей воспроизводимого benchmark."""
    текст = _текст().lower()
    поля = {
        "сырые запросы": bool(re.search(r"raw queries|сыр(?:ые|ых) запрос", текст)),
        "эталонные ответы": bool(re.search(r"ground[- ]truth|эталонн(?:ые|ых) ответ", текст)),
        "разбиение": bool(re.search(r"train/test split|разбиени[ея] на обуча|разбиени[ея]", текст)),
        "seed": bool(re.search(r"\bseed\b|начальн(?:ое|ого) состояни", текст)),
        "версия реализации": bool(re.search(r"commit|верси[яи] реализации|контрольн(?:ая|ой) сумм", текст)),
        "независимый повтор": bool(re.search(r"independent replay|independent run|независим(?:ый|ая) повтор", текст)),
    }
    поля["рецепт_полон"] = all(поля.values())
    поля["отсутствует"] = [имя for имя, есть in поля.items() if имя not in {"рецепт_полон", "отсутствует"} and not есть]
    return поля


def _самопроверка():
    assert наблюдение() == {"правильные": 162.0, "запросы": 166.0, "процент": 97.6}
    эт = эталон()
    assert эт["правильные"] == 162.0 and эт["запросы"] == 166.0
    assert abs(эт["процент"] - 100.0 * 162.0 / 166.0) < 1.0e-14
    алт = эталон_альт()
    assert алт["правильные"] == эт["правильные"] and алт["запросы"] == эт["запросы"]
    assert abs(алт["процент"] - эт["процент"]) < 1.0e-14
    assert _контроль_полной_регрессии() == {"правильные": 415.0, "запросы": 419.0, "процент": 100.0 * 415.0 / 419.0, "пропуски": 4.0, "ошибки": 0.0}
    assert _неверная_подстановка() != наблюдение()
    инвентарь = _рецепт_полон()
    assert not инвентарь["рецепт_полон"]
    assert "сырые запросы" in инвентарь["отсутствует"]
    assert "эталонные ответы" in инвентарь["отсутствует"]
    assert "независимый повтор" in инвентарь["отсутствует"]


_самопроверка()

