"""Аудит воспроизводимости заявления GF16 на обученной MLP MNIST.

Кейс не превращает совпадение двух строк точности в подтверждение. Он
проверяет, хватает ли отчёта для независимого воспроизведения: датасета,
разбиения, контрольной точки модели, seed, версии кода и полного протокола.
"""
import os
import re
import sys
from goldsieve.sieve import Claim

ИСТОЧНИК = "/home/user/workspace/corpus/trinity/docs/research/gf16_vs_literature.md"
if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться без регистрации в sys.modules")

def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт GF16 отсутствует")
    return open(ИСТОЧНИК, encoding="utf-8").read()

def _строка_формата(формат):
    текст = _текст()
    маркер = "Trained MNIST MLP"
    if маркер not in текст:
        raise AssertionError("раздел BENCH-004b отсутствует")
    текст = текст.split(маркер, 1)[1]
    совпадение = re.search(
        rf"^\|\s*{re.escape(формат)}\s*\|\s*([0-9.]+)\s*\|\s*([0-9.]+)",
        текст, re.MULTILINE)
    if not совпадение:
        raise AssertionError(f"строка {формат} не найдена")
    return float(совпадение.group(1)), float(совпадение.group(2))

def наблюдение():
    # Отдельный путь: таблица BENCH-004b, точность GF16.
    значение, _ = _строка_формата("GF16")
    return значение

def _контроль():
    значение, _ = _строка_формата("ternary")
    return значение

def _инвентарь_рецепта():
    текст = _текст().lower()
    поля = {
        "датасет": bool(re.search(r"mnist", текст)),
        "разбиение": bool(re.search(r"train.?test split|разбиен|test set", текст)),
        "архитектура": bool(re.search(r"mlp 784.?→?128|784.?128.?10", текст)),
        "контрольная точка модели": bool(re.search(r"checkpoint|sha256|hash", текст)),
        "seed": bool(re.search(r"\bseed\b|random state", текст)),
        "версия кода": bool(re.search(r"commit|git sha|release version", текст)),
        "полный набор входов": bool(re.search(r"dataset archive|raw inputs|test images", текст)),
        "критерий оценки": bool(re.search(r"accuracy definition|top.?1|correct predictions", текст)),
    }
    поля["рецепт_полон"] = all(поля.values())
    поля["отсутствует"] = [имя for имя, есть in поля.items()
                           if имя not in {"рецепт_полон", "отсутствует"} and not есть]
    return поля

def _код_причины():
    return "" if _инвентарь_рецепта()["рецепт_полон"] else "metrics_incommensurable"

def _неверный_ответ():
    return 50.0

def _самопроверка():
    assert abs(наблюдение() - 97.67) < 1e-12
    assert abs(_контроль() - 9.80) < 1e-12
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["рецепт_полон"]
    assert set(инвентарь["отсутствует"]) == {
        "разбиение", "контрольная точка модели", "seed", "версия кода", "полный набор входов",
        "критерий оценки",
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _неверный_ответ() != наблюдение()
    assert _контроль() != наблюдение()

_самопроверка()

