from goldsieve.sieve import Claim


ИСТОЧНИК_JSON = "/home/user/workspace/corpus/trinity/data/results/cifar10_metrics.json"
ИСТОЧНИК_CSV = "/home/user/workspace/corpus/trinity/data/results/cifar10_summary.csv"

# Реальный CLI загружает модуль через module_from_spec без регистрации в
# sys.modules; запрещаем тихую замену этого пути на обычный импорт.
if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться без регистрации в sys.modules")


def _json():
    with open(ИСТОЧНИК_JSON, encoding="utf-8") as файл:
        return json.load(файл)


def _csv():
    with open(ИСТОЧНИК_CSV, encoding="utf-8", newline="") as файл:
        return list(csv.DictReader(файл))


def наблюдение():
    данные = _json()
    значение = данные["results"]["fp16"]["accuracy_percent"]
    if not isinstance(значение, (int, float)):
        raise AssertionError("точность fp16 не числова")
    return float(значение)


def _наблюдение_альт():
    строки = _csv()
    для_fp16 = [строка for строка in строки if строка.get("format") == "fp16"]
    if len(для_fp16) != 1:
        raise AssertionError("в CSV не ровно одна строка fp16")
    return float(для_fp16[0]["accuracy_percent"])


def _инвентарь_рецепта():
    данные = _json()
    текст = json.dumps(данные, ensure_ascii=False).lower()
    обязательные = {
        "датасет": "dataset",
        "размер выборки": "samples",
        "архитектура": "architecture",
        "разбиение": "split",
        "предобработка": "preprocess",
        "контрольная сумма модели": "checkpoint",
        "начальное состояние": "seed",
        "определение точности": "accuracy_definition",
        "агрегация потерь": "loss_aggregation",
        "выходы модели": "logits",
    }
    наличие = {имя: (ключ in текст) for имя, ключ in обязательные.items()}
    наличие["сопоставимо"] = all(наличие.values())
    наличие["отсутствует"] = [имя for имя, есть in наличие.items()
                              if имя not in {"сопоставимо", "отсутствует"}
                              and not есть]
    return наличие


def _код_причины():
    return "" if _инвентарь_рецепта()["сопоставимо"] else "metrics_incommensurable"


def _неверный_ответ():
    return 50.0


def _контроль():
    строки = _csv()
    для_f32 = [строка for строка in строки if строка.get("format") == "f32"]
    if len(для_f32) != 1:
        raise AssertionError("в CSV не ровно одна строка f32")
    return float(для_f32[0]["accuracy_percent"])


def _самопроверка():
    assert abs(наблюдение() - 99.99) < 1e-12
    assert abs(_наблюдение_альт() - наблюдение()) < 1e-12
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["сопоставимо"]
    assert set(инвентарь["отсутствует"]) == {
        "разбиение", "предобработка", "контрольная сумма модели",
        "начальное состояние", "определение точности", "агрегация потерь",
        "выходы модели",
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _неверный_ответ() != наблюдение()
    assert _контроль() != наблюдение()


_самопроверка()


