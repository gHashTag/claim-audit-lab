def _multiplicity_for(target):
    """Сколько попаданий в ЭТУ цель даёт случай при её собственной погрешности.

    Ключевой момент честности: eps берётся не из заявленной точности корпуса, а
    из погрешности самого измерения. Полоса шириной +-sigma вокруг измеренного
    значения — это всё, что эксперимент вообще различает; попадание внутрь неё
    надо сравнивать с тем, сколько членов семейства туда попадает случайно.
    Границы берём ЭФФЕКТИВНЫЕ (те, что реально использованы в таблицах), а не
    объявленные — иначе поправка на множественность занижена.
    """
    def _m():
        tgt = target()
        value = float(tgt["value"])
        eps = float(tgt["uncertainty"]) / abs(value)
        ranges = {"n": range(1, 10), "k": range(-6, 7), "m": range(-4, 5),
                  "p": range(-6, 7), "q": range(-4, 5)}
        frac, exp_hits = family.empirical_multiplicity(
            (-1, 4), eps, ranges=ranges, trials=600, seed=11)
        # p_глоб: вероятность, что хотя бы одно попадание случится случайно
        p_glob = frac
        return {
            "expected_hits": exp_hits,
            "p_global": p_glob,
            "fraction_random_targets_hit": frac,
        }
    return _m


