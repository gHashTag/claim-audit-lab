"""Аудит заявленной средней ошибки в таблице физических отношений.

Наблюдение извлекается из заголовка раздела. Эталон заново считает среднее
пяти явно приведённых строк таблицы; альтернативный путь использует
statistics.fmean по тем же извлечённым значениям. Число 0,012 не подмешивается
в эталон.
"""

import re
import statistics
from decimal import Decimal

from goldsieve.sieve import Claim


ИСТОЧНИК = "/home/user/workspace/corpus/trinity/docs/papers/README_FOR_SCIENTISTS.md"


def _текст():
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def _строки_таблицы():
    """Извлечь ошибки пяти строк до заголовка CKM."""
    строки = []
    в_таблице = False
    for строка in _текст().splitlines():
        if строка.startswith("| Parameter | Formula | Value | Error |"):
            в_таблице = True
            continue
        if в_таблице and строка.startswith("**CKM Matrix"):
            break
        if not в_таблице or not строка.startswith("|") or строка.startswith("|---"):
            continue
        ячейки = [ячейка.strip() for ячейка in строка.strip().strip("|").split("|")]
        if len(ячейки) != 5:
            continue
        совпадение = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)%", ячейки[3])
        if совпадение:
            строки.append(Decimal(совпадение.group(1)))
    if len(строки) != 5:
        raise AssertionError("ожидались пять строк таблицы физических отношений")
    return строки


def _наблюдение():
    совпадение = re.search(
        r"Particle Physics \(22 relations, avg\. error ([0-9.]+)%\)", _текст()
    )
    if not совпадение:
        raise AssertionError("заголовок средней ошибки не найден")
    return float(совпадение.group(1))


def _эталон():
    значения = _строки_таблицы()
    return float(sum(значения) / Decimal(len(значения)))


def _эталон_альт():
    значения = [float(значение) for значение in _строки_таблицы()]
    return statistics.fmean(значения)


def _неверный_ответ():
    return 0.001


def _отрицательный_контроль():
    return _наблюдение()


def _выборка():
    return [float(значение) for значение in _строки_таблицы()]


def _среднее(значения):
    return float(sum(значения) / len(значения))


def _самопроверка():
    assert _наблюдение() == 0.012
    assert _строки_таблицы() == [Decimal("0.002"), Decimal("0.005"), Decimal("0.009"), Decimal("0.003"), Decimal("0.008")]
    assert abs(_эталон() - 0.0054) < 1.0e-12
    assert abs(_эталон_альт() - _эталон()) < 1.0e-12
    assert _неверный_ответ() != _эталон()
    assert _отрицательный_контроль() != _эталон()


_самопроверка()


