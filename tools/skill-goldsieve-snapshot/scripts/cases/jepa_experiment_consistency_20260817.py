"""Аудит внутренней согласованности временного T-JEPA benchmark.

Наблюдение извлекается из сводки Key Findings, а эталон отдельно строится
из строк таблицы Results. Проверяется не простое отношение чисел, а новый
риск: выбор лучшего шага и сводный результат должны быть согласованы с
полным временным рядом; это не доказывает качество модели вне отчёта.
"""
import csv
import os
import re
import sys

from goldsieve.sieve import Claim

ИСТОЧНИК = "/home/user/workspace/corpus/trinity/docs/research/JEPAT/experiments.md"

if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться через module_from_spec без регистрации")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт T-JEPA отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def _строки_таблицы():
    строки = _текст().splitlines()
    try:
        начало = строки.index("| Step | MSE | AvgMSE10 | ReprVar |") + 2
    except ValueError as exc:
        raise AssertionError("таблица Results не найдена") from exc
    найдено = []
    for строка in строки[начало:]:
        if not строка.startswith("|"):
            break
        совпадение = re.match(r"\|\s*\**(\d+)\**\s*\|\s*\**([0-9.]+)", строка)
        if совпадение:
            найдено.append((int(совпадение.group(1)), float(совпадение.group(2))))
    if len(найдено) != 12:
        raise AssertionError("ожидались двенадцать точек временного ряда")
    return найдено


def наблюдение():
    """Извлечь сводку MSE и лучший шаг из Key Findings."""
    совпадение = re.search(
        r"\*\*MSE:\*\*\s*([0-9.]+)\s*→\s*([0-9.]+)\s*\(best @ step (\d+)\)",
        _текст(),
    )
    if not совпадение:
        raise AssertionError("сводка MSE не найдена")
    начало, конец, шаг = совпадение.groups()
    return {"начало": float(начало), "конец": float(конец), "лучший_шаг": float(шаг)}


def эталон():
    """Вывести минимум MSE и его шаг из полного временного ряда."""
    ряд = _строки_таблицы()
    шаг, значение = min(ряд, key=lambda пара: (пара[1], пара[0]))
    return {
        "начало": ряд[0][1],
        "конец": значение,
        "лучший_шаг": float(шаг),
    }


def эталон_альт():
    """Альтернативный метод: CSV-разбор ячеек Markdown с Decimal-путём."""
    строки = _текст().splitlines()
    внутри = False
    найдено = []
    for строка in строки:
        if строка.strip() == "| Step | MSE | AvgMSE10 | ReprVar |":
            внутри = True
            continue
        if not внутри:
            continue
        if not строка.startswith("|"):
            break
        поля = [поле.strip().replace("**", "") for поле in next(csv.reader([строка], delimiter="|"))]
        поля = [поле for поле in поля if поле]
        if len(поля) >= 2 and поля[0].isdigit():
            найдено.append((int(поля[0]), float(поля[1])))
    if len(найдено) != 12:
        raise AssertionError("альтернативный разбор не нашёл временной ряд")
    шаг, значение = min(найдено, key=lambda пара: (пара[1], пара[0]))
    return {"начало": найдено[0][1], "конец": значение, "лучший_шаг": float(шаг)}


def _неверная_подстановка():
    return {"начало": 1.95, "конец": 0.30, "лучший_шаг": 5000.0}


def _контроль():
    """Контроль берёт минимум AvgMSE10, это другая колонка, не MSE."""
    строки = _текст().splitlines()
    значения = []
    for строка in строки:
        совпадение = re.match(r"\|\s*(\d+)\s*\|\s*[0-9.]+\s*\|\s*([0-9.]+)", строка)
        if совпадение:
            значения.append((int(совпадение.group(1)), float(совпадение.group(2))))
    шаг, значение = min(значения, key=lambda пара: (пара[1], пара[0]))
    return {"лучший_шаг": float(шаг), "avg_mse10": значение}


def _терпимость_альт():
    return 1.0e-12


def _самопроверка():
    assert наблюдение() == {"начало": 1.95, "конец": 0.30, "лучший_шаг": 3965.0}
    эт = эталон()
    assert эт == {"начало": 1.812, "конец": 0.302, "лучший_шаг": 3965.0}
    assert эталон_альт() == эт
    assert _неверная_подстановка() != эт
    assert _контроль()["лучший_шаг"] == 3000.0


_самопроверка()

