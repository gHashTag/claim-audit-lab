def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Golden Chain Final Report отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def наблюдение():
    """Извлечь напечатанный агрегат из строки Overall."""
    совпадение = re.search(
        r"\|\s*\*\*Overall\*\*\s*\|\s*\*\*(\d+)%\s*\((\d+)/(\d+)\)\*\*",
        _текст(),
    )
    if not совпадение:
        raise AssertionError("строка Overall не найдена")
    процент, готово, всего = map(int, совпадение.groups())
    return {"готово": float(готово), "всего": float(всего), "процент": float(процент)}


def _детальные_строки():
    """Выделить строки таблицы Tech Tree Progress регулярным разбором."""
    строки = _текст().splitlines()
    начало = строки.index("| Branch | Progress | Status |") + 2
    итог = []
    for строка in строки[начало:]:
        if not строка.startswith("|"):
            break
        совпадение = re.search(r"\|\s*(\d+)%\s*\((\d+)/(\d+)\)\s*\|", строка)
        if совпадение:
            итог.append(tuple(map(int, совпадение.groups())))
    if len(итог) != 7:
        raise AssertionError("ожидались семь детальных строк прогресса")
    return итог


def эталон():
    """Вывести согласованный агрегат суммированием детальных строк."""
    строки = _детальные_строки()
    готово = sum(готово for _, готово, _ in строки)
    всего = sum(всего for _, _, всего in строки)
    return {"готово": float(готово), "всего": float(всего),
            "процент": float(100.0 * готово / всего)}


def эталон_альт():
    """Альтернативный метод: табличный разбор с Decimal и CSV-парсером."""
    найдено = []
    в_таблице = False
    for строка in _текст().splitlines():
        if строка.strip() == "| Branch | Progress | Status |":
            в_таблице = True
            continue
        if not в_таблице:
            continue
        if not строка.startswith("|"):
            break
        поля = next(csv.reader([строка], delimiter="|"))
        ячейки = [поле.strip() for поле in поля]
        if len(ячейки) < 3:
            continue
        совпадение = re.fullmatch(r"(\d+)%\s*\((\d+)/(\d+)\)", ячейки[2])
        if совпадение:
            найдено.append(tuple(Decimal(x) for x in совпадение.groups()))
    if len(найдено) != 7:
        raise AssertionError("альтернативный разбор не нашёл семь строк")
    готово = sum(строка[1] for строка in найдено)
    всего = sum(строка[2] for строка in найдено)
    процент = Decimal(100) * готово / всего
    return {"готово": float(готово), "всего": float(всего), "процент": float(процент)}


def _нулевая_модель():
    """Независимый контроль: верхний блок фаз, а не Tech Tree."""
    совпадение = re.search(r"^### .*Completed \((\d+)/(\d+)\)", _текст(), re.M)
    if not совпадение:
        raise AssertionError("контроль завершённых фаз не найден")
    готово, всего = map(int, совпадение.groups())
    return {"готово": float(готово), "всего": float(всего),
            "процент": 100.0 * готово / всего}


def _неверная_подстановка():
    return {"готово": 40.0, "всего": 54.0, "процент": 74.07407407407408}


def _терпимость_альт():
    return 1.0e-12


def _самопроверка():
    assert наблюдение() == {"готово": 42.0, "всего": 54.0, "процент": 78.0}
    эт = эталон()
    assert эт["готово"] == 39.0 and эт["всего"] == 42.0
    assert abs(эт["процент"] - 100.0 * 39.0 / 42.0) < 1.0e-14
    алт = эталон_альт()
    assert алт["готово"] == эт["готово"] and алт["всего"] == эт["всего"]
    assert abs(алт["процент"] - эт["процент"]) < 1.0e-14
    assert _нулевая_модель() == {
        "готово": 1.0, "всего": 9.0,
        "процент": 11.11111111111111,
    }
    assert _неверная_подстановка() != наблюдение()
    assert _нулевая_модель() != эталон()


_самопроверка()

