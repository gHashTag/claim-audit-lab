ИСТОЧНИК_СКРИПТА = "/home/user/workspace/corpus/trinity/scripts/height_extrapolation.py"
ИСТОЧНИК_НУЛЕЙ = "/home/user/workspace/corpus/trinity/data/zeta/zeros_odlyzko_100k.txt"

_КЭШ = {}


def _нули():
    if "нули" not in _КЭШ:
        _КЭШ["нули"] = np.loadtxt(ИСТОЧНИК_НУЛЕЙ)
    return _КЭШ["нули"]


def _тэта(t):
    t = np.asarray(t, dtype=float)
    return np.imag(loggamma(0.25 + 0.5j * t)) - 0.5 * t * math.log(math.pi)


def _развёртка(gamma):
    return np.diff(_тэта(gamma)) / math.pi


def _статистика(значения):
    return float(np.std(значения, ddof=1))


def _точки_высот():
    """Десять полос равного числа нулей, как в исходном рецепте."""
    gamma = _нули()
    n = 10
    размер = len(gamma) // n
    точки = []
    for i in range(n):
        g = gamma[i * размер:(i + 1) * размер + 1]
        s = _развёртка(g)
        x = float(1.0 / np.mean(np.log(g[:-1] / (2.0 * math.pi))))
        точки.append((x, _статистика(s), float(g[0]), float(g[-1])))
    return точки


def _свободный_член_numpy(точки):
    x = np.asarray([p[0] for p in точки], dtype=float)
    y = np.asarray([p[1] for p in точки], dtype=float)
    наклон, свободный = np.polyfit(x, y, 1)
    return float(свободный), float(наклон)


def _свободный_член_центрованный(точки):
    """Альтернатива: центрированные суммы, без вызова polyfit."""
    x = [p[0] for p in точки]
    y = [p[1] for p in точки]
    xm = statistics.fmean(x)
    ym = statistics.fmean(y)
    наклон = sum((a - xm) * (b - ym) for a, b in zip(x, y)) / sum((a - xm) ** 2 for a in x)
    return float(ym - наклон * xm), float(наклон)


def _заявлено():
    with open(ИСТОЧНИК_СКРИПТА, encoding="utf-8") as handle:
        text = handle.read()
    match = re.search(r'EXACT\s*=\s*\{"std":\s*([0-9.]+)', text)
    if not match:
        raise AssertionError("заявленный свободный член не найден")
    return {"std": float(match.group(1))}


def _наблюдение():
    свободный, наклон = _свободный_член_numpy(_точки_высот())
    return {"std": свободный, "slope": наклон}


def _эталон():
    if "точный" not in _КЭШ:
        _КЭШ["точный"] = {"std": GapLaw(h=2.0e-3, n=100).std()}
    return dict(_КЭШ["точный"])


def _эталон_альт():
    """Независимый эталон: GUE-матрицы, а не детерминант ядра."""
    if "монте" not in _КЭШ:
        _КЭШ["монте"] = {"std": mc_summary(n=400, reps=12, seed=20260816)["std"]}
    return dict(_КЭШ["монте"])


def _допуск_альт():
    # Для 400x12 матриц разброс второго метода измерен отдельным MC-прогоном;
    # 5 % — консервативная граница, а не точность первого эталона.
    return 0.05


def _неверно():
    return {"std": 1.0, "slope": 0.0}


def _позитивный_контроль():
    """Посаженная линейная зависимость: свободный член должен быть 0,424257."""
    x = [0.05, 0.10, 0.15, 0.20]
    y = [0.4242576222440628 + 2.5 * a for a in x]
    return {"std": _свободный_член_центрованный([(a, b, 0.0, 0.0) for a, b in zip(x, y)])[0]}


def _самопроверка():
    assert _заявлено() == {"std": 0.424258}
    точки = _точки_высот()
    assert len(точки) == 10
    primary = _свободный_член_numpy(точки)
    alternate = _свободный_член_центрованный(точки)
    assert abs(primary[0] - alternate[0]) < 1e-12
    assert abs(primary[0] - 0.428899) < 2e-5
    assert abs(_эталон()["std"] - 0.42425762224406265) < 1e-9
    assert abs(_позитивный_контроль()["std"] - 0.4242576222440628) < 1e-12
    assert _неверно() != _эталон()


_самопроверка()


