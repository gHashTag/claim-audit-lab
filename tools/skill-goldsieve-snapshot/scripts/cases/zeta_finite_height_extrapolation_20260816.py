"""Аудит заявления о полной конечновысотной поправке для нулей дзета.

Источник корпуса описывает линейную экстраполяцию статистики по 1/L и
утверждает, что свободный член совпадает с точным GUE. Наблюдение здесь
пересчитывается из сырых нулей отдельным кодом; напечатанное значение EXACT
используется только как заявленное, не как эталон. Эталон точного GUE строится
детерминантом Фредгольма методом Нюстрёма. Независимый контроль эталона
получается другим путём — Монте-Карло по случайным эрмитовым матрицам GUE.

Этот кейс проверяет новый observable (свободный член экстраполяции по 1/L) и
новую модель (линейная конечновысотная поправка), а не прежнюю масштабную
деформацию BBLM. Результат не распространяется на полную теорию поправок.
"""

