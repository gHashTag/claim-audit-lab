"""Аудит 99-го процентиля расстояний между нулями дзета.

Наблюдение извлекается из строки сводки корпуса. Эталон вычисляется
независимо по точному закону зазора GUE через детерминант Фредгольма.
Второй эталон использует формулу Вигнера—сюрмиса. Подставка и пуассоновский
контроль должны быть отвергнуты тем же каскадом.
"""

import re

from goldsieve.refs.gue_exact_gap import GapLaw, surmise_quantile
from goldsieve.sieve import Claim

ИСТОЧНИК_СВОДКИ = (
    "/home/user/workspace/corpus/trinity/data/zeta/"
    "zeta_gue_analysis_results.md"
)
ИСТОЧНИК_НУЛЕЙ = (
    "/home/user/workspace/corpus/trinity/data/zeta/zeros_odlyzko_100k.txt"
)


def _текст():
    with open(ИСТОЧНИК_СВОДКИ, encoding="utf-8") as файл:
        return файл.read()


def _наблюдение():
    совпадение = re.search(r"\| 99th percentile \| ([0-9.]+) \|", _текст())
    if not совпадение:
        raise AssertionError("строка 99-го процентиля не найдена")
    return float(совпадение.group(1))


def _эталон():
    """Точный GUE: интеграл Fredholm с синус-ядром, не число из отчёта."""
    return float(GapLaw(h=2.0e-3, n=100).quantile(0.99))


def _эталон_альт():
    """Второй принципиально иной эталон: Wigner—surmise."""
    return float(surmise_quantile(0.99))


def _подставка():
    return 1.0


def _контроль_пуассона():
    return 4.605170185988091


def _самопроверка():
    assert _наблюдение() == 2.0680
    точный = _эталон()
    assert 2.0 < точный < 2.2
    assert abs(_эталон_альт() - точный) / точный < 0.02
    assert _подставка() != точный
    assert _контроль_пуассона() != точный


_самопроверка()


