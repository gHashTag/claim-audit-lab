"""Проверка воспроизводимости отчёта Cycle 46 о планировании по дедлайну.

Кейс не сравнивает напечатанные 1,0 и 0,618: это было бы дешёвое
арифметическое подтверждение. Он проверяет полноту рецепта benchmark EDF,
раздельно извлекает наблюдение и контроль и оставляет вопрос, если полного
независимого запуска нет.
"""
import os
import re
import sys
from goldsieve.sieve import Claim

ИСТОЧНИК = "/home/user/workspace/corpus/trinity/deploy/trinity-nexus/docs/research/cycle46-deadline-scheduling-report.md"
if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться без регистрации в sys.modules")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Cycle 46 отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def наблюдение():
    совпадение = re.search(r"\| Improvement Rate \| ([0-9.]+) \|", _текст())
    if not совпадение:
        raise AssertionError("коэффициент улучшения не найден")
    значение = float(совпадение.group(1))
    if значение != 1.0:
        raise AssertionError("коэффициент улучшения изменился")
    return значение


def _контроль():
    совпадение = re.search(r"\| Tests Passed \| (\d+)/(\d+) \|", _текст())
    if not совпадение:
        raise AssertionError("контроль числа тестов не найден")
    пройдено, всего = map(int, совпадение.groups())
    return float(пройдено) / float(всего) * 100.0


def _эталон_контроля_из_таблицы():
    """Вычисляемый вспомогательный эталон, не используемый как вердикт.

    Он строится из двух полей таблицы и нужен только для проверки, что
    контроль читается как составной объект, а не как заранее записанный
    литерал. Для основного benchmark эталон намеренно отсутствует: нет сырой
    нагрузки и независимого исполнителя.
    """
    совпадение = re.search(r"\| Tests Passed \| (\d+)/(\d+) \|", _текст())
    if not совпадение:
        raise AssertionError("эталон контроля не вычисляется")
    пройдено, всего = (int(часть) for часть in совпадение.groups())
    return {"пройдено": пройдено, "всего": всего,
            "доля": пройдено / всего if всего else 0.0}


def _инвентарь_рецепта():
    текст = _текст().lower()
    поля = {
        "сырые задания": bool(re.search(r"raw jobs|job list|input jobs|исходн(?:ые|ый) задания", текст)),
        "точная реализация": bool(re.search(r"commit sha|git commit|git sha|точн(?:ая|ый) версия кода", текст)),
        "среда выполнения": bool(re.search(r"python|zig version|compiler version|операционная система", текст)),
        "контрольная сумма входа": bool(re.search(r"sha256|checksum|input hash|контрольная сумма", текст)),
        "границы времени": bool(re.search(r"clock source|time resolution|границ(?:ы|а) времени", текст)),
        "независимый повтор": bool(re.search(r"independent replay|independent run|independent reproduction|независим(?:ый|ая) повтор", текст)),
        "seed": bool(re.search(r"\bseed\b|random state", текст)),
        "рецепт_полон": False,
    }
    поля["рецепт_полон"] = all(поля[имя] for имя in поля if имя != "рецепт_полон")
    поля["отсутствует"] = [имя for имя, есть in поля.items()
                           if имя not in {"рецепт_полон", "отсутствует"} and not есть]
    return поля


def _код_причины():
    return "" if _инвентарь_рецепта()["рецепт_полон"] else "metrics_incommensurable"


def _неверный_ответ():
    return 0.5


def _самопроверка():
    assert наблюдение() == 1.0
    assert _контроль() == 100.0
    эталон = _эталон_контроля_из_таблицы()
    assert эталон == {"пройдено": 276, "всего": 276, "доля": 1.0}
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["рецепт_полон"]
    assert set(инвентарь["отсутствует"]) == {
        "сырые задания", "точная реализация", "среда выполнения",
        "контрольная сумма входа", "границы времени", "независимый повтор", "seed",
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _неверный_ответ() != наблюдение()
    assert _контроль() != наблюдение()


_самопроверка()

