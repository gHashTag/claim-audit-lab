"""Проверка сопоставимости train loss и train PPL в отчёте v2.40.

Приказ пользователя запрещает объявлять ошибкой числа, полученные из
несопоставимых метрик. Этот кейс не подставляет exp(loss) вместо отсутствующего
рецепта: он машинно проверяет, раскрыты ли общая шкала, токенизация,
усреднение и стадия обучения.
"""

import os
import re

from goldsieve.sieve import Claim


ИСТОЧНИК = (
    "/home/user/workspace/corpus/trinity/docs/docs/research/"
    "trinity-golden-chain-v2-40-large-corpus-report.md"
)


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Golden Chain v2.40 отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def _потеря():
    совпадение = re.search(
        r"Large corpus train loss:\s+([0-9]+\.[0-9]+)", _текст()
    )
    if not совпадение:
        raise AssertionError("строка train loss не найдена")
    return float(совпадение.group(1))


def _перплексия():
    совпадение = re.search(
        r"Large corpus train PPL:\s+([0-9]+\.[0-9]+)", _текст()
    )
    if not совпадение:
        raise AssertionError("строка train PPL не найдена")
    return float(совпадение.group(1))


def _инвентарь_рецепта():
    """Проверить обязательные поля общей шкалы, не угадывая их."""
    текст = _текст().lower()
    # Слова из других разделов отчёта (например, «average» в описании
    # обучения или «step» в дорожной карте) не считаются рецептом метрики.
    строки_метрик = "\n".join(
        строка for строка in текст.splitlines()
        if "loss" in строка or "ppl" in строка
    )
    поля = {
        "шкала": bool(re.search(
            r"\b(?:nat|nats|bits?|бит(?:а|ов)?)\b", строки_метрик
        )),
        "токенизация": bool(re.search(
            r"tokeniz|токенизац|tokens?\s+per|токен(?:ов|а)?",
            строки_метрик
        )),
        "усреднение": bool(re.search(
            r"averag|mean\s+(?:loss|nll)|reduction|усредн|средн(?:ее|яя)\s+"
            r"(?:потер|ошибк|loss)", строки_метрик
        )),
        "стадия": bool(re.search(
            r"\b(?:stage|epoch|step|шаг(?:е|а)?\s+обуч|стади[яи]\s+обуч)",
            строки_метрик
        )),
    }
    поля["сопоставимо"] = all(поля.values())
    поля["отсутствует"] = [имя for имя, есть in поля.items()
                           if имя != "сопоставимо" and not есть]
    return поля


def _код_причины():
    """Выдать reason-code только из измеренного результата проверки."""
    return ("" if _инвентарь_рецепта()["сопоставимо"]
            else "metrics_incommensurable")


def _неверный_ответ():
    return 1.42


def _контроль():
    """Отдельное контрольное число тестовой метрики из того же отчёта."""
    совпадение = re.search(
        r"Large corpus test PPL:\s+([0-9]+\.[0-9]+)", _текст()
    )
    if not совпадение:
        raise AssertionError("строка test PPL не найдена")
    return float(совпадение.group(1))


def _самопроверка():
    assert abs(_потеря() - 0.8066) < 1.0e-12
    assert abs(_перплексия() - 1.87) < 1.0e-12
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["сопоставимо"]
    assert set(инвентарь["отсутствует"]) == {
        "шкала", "токенизация", "усреднение", "стадия"
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _неверный_ответ() != _перплексия()
    assert _контроль() != _перплексия()


_самопроверка()


