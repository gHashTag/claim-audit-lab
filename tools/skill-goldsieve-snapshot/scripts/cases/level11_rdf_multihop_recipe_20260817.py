"""Проверка воспроизводимости отчёта Level 11.2 о RDF и многошаговом выводе.

Наблюдение извлекается из сводной таблицы. Эталон строится из отдельных
строк подробных тестов, а альтернативный эталон — отдельным разбором таблицы.
Это не подтверждение отношения напечатанных чисел: обязательные входы
benchmark, полный код, начальное состояние и независимый повтор отсутствуют.
"""
import csv
