import sys

from goldsieve.sieve import Claim

ИСТОЧНИК = (
    "/home/user/workspace/corpus/trinity/deploy/trinity-nexus/docs/research/"
    "trinity-level11-rdf-multi-hop-report.md"
)

ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ_РЕЦЕПТА = (
    "исходные векторы",
    "исходные запросы",
    "полная разметка",
    "контрольная сумма входов",
    "начальное состояние",
    "версия реализации",
    "независимый повтор",
)

if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться через module_from_spec без регистрации в sys.modules")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Level 11.2 отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def _доля(фрагмент):
    совпадение = re.search(r"(\d+)\s*/\s*(\d+)", фрагмент)
    if not совпадение:
        raise AssertionError("доля не найдена: %s" % фрагмент)
    return float(совпадение.group(1)), float(совпадение.group(2))


def наблюдение():
    """Извлечь три агрегата из сводной таблицы Key Metrics."""
    текст = _текст()
    шаблоны = {
        "rdf": r"\|\s*RDF Triple Query\s*\|\s*\*\*(\d+\s*/\s*\d+)\s*\([^)]*\)\*\*",
        "многошаговый": r"\|\s*Multi-Hop Inference\s*\|\s*\*\*(\d+\s*/\s*\d+)\s*\([^)]*\)\*\*",
        "суперпозиция": r"\|\s*Graph Superposition\s*\|\s*\*\*(\d+\s*/\s*\d+)\s*\([^)]*\)\*\*",
    }
    ответ = {}
    for имя, шаблон in шаблоны.items():
        совпадение = re.search(шаблон, текст, re.I)
        if not совпадение:
            raise AssertionError("строка сводки не найдена: %s" % имя)
        правильные, всего = _доля(совпадение.group(1))
        ответ[имя + "_правильные"] = правильные
        ответ[имя + "_всего"] = всего
    ответ["полнота_рецепта"] = 0.0 if not _инвентарь_рецепта()["рецепт_полон"] else 1.0
    return ответ


def _подробные_строки():
    """Извлечь результаты Test 58–60 из подробных блоков отчёта."""
    текст = _текст()
    шаблоны = {
        "rdf": r"Bipolar query accuracy:\s*(\d+\s*/\s*\d+)",
        "многошаговый": r"Multi-hop accuracy:\s*(\d+\s*/\s*\d+)",
        "суперпозиция": r"Superposed graph query accuracy:\s*(\d+\s*/\s*\d+)",
    }
    ответ = {}
    for имя, шаблон in шаблоны.items():
        совпадение = re.search(шаблон, текст, re.I)
        if not совпадение:
            raise AssertionError("подробная строка не найдена: %s" % имя)
        правильные, всего = _доля(совпадение.group(1))
        ответ[имя + "_правильные"] = правильные
        ответ[имя + "_всего"] = всего
    ответ["полнота_рецепта"] = 0.0 if not _инвентарь_рецепта()["рецепт_полон"] else 1.0
    return ответ


def эталон():
    """Эталон подробных метрик и полного, заранее заданного рецепта.

    Полнота — не число из отчёта: это вычисленная доля обязательных элементов
    воспроизводимого benchmark-рецепта. Поэтому отсутствие элементов в отчёте
    даёт измеримое расхождение, а не совпадение наблюдения с самим собой.
    """
    ответ = _подробные_строки()
    ответ["полнота_рецепта"] = float(
        len(ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ_РЕЦЕПТА) / len(ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ_РЕЦЕПТА)
    )
    return ответ


def эталон_альт():
    """Альтернативный эталон: CSV-разбор только таблицы Key Metrics."""
    найдено = {}
    в_таблице = False
    for строка in _текст().splitlines():
        if строка.strip() == "| Metric | Value | Notes |":
            в_таблице = True
            continue
        if not в_таблице:
            continue
        if not строка.startswith("|"):
            if найдено:
                break
            continue
        ячейки = [поле.strip() for поле in next(csv.reader([строка], delimiter="|"))]
        if len(ячейки) < 3:
            continue
        имя = ячейки[1].lower()
        соответствия = (
            ("rdf triple query", "rdf"),
            ("multi-hop inference", "многошаговый"),
            ("graph superposition", "суперпозиция"),
        )
        for ключ, короткое in соответствия:
            if ключ in имя:
                совпадение = re.search(r"(\d+\s*/\s*\d+)", ячейки[2])
                if совпадение:
                    правильные, всего = _доля(совпадение.group(1))
                    найдено[короткое + "_правильные"] = правильные
                    найдено[короткое + "_всего"] = всего
    if len(найдено) != 6:
        raise AssertionError("альтернативная таблица не дала три результата")
    найдено["полнота_рецепта"] = float(
        len(ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ_РЕЦЕПТА) / len(ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ_РЕЦЕПТА)
    )
    return найдено


def _контроль_регрессии():
    """Отрицательный контроль с той же формой, но без RDF-сигнала.

    Общий счётчик регрессии не имеет ключей RDF и поэтому молча сравнивался
    с пустым пересечением ключей; это превращало С5 в ложный VOID. Контроль
    теперь сохраняет форму наблюдаемого словаря и задаёт нулевую точность
    при тех же размерах трёх наборов. Независимый счётчик тестов остаётся
    отдельной проверкой ниже.
    """
    _контроль_регрессии.общий_счётчик = _общий_счётчик_тестов()
    return {
        "rdf_правильные": 0.0,
        "rdf_всего": 24.0,
        "многошаговый_правильные": 0.0,
        "многошаговый_всего": 4.0,
        "суперпозиция_правильные": 0.0,
        "суперпозиция_всего": 6.0,
        "полнота_рецепта": 0.0,
    }


def _общий_счётчик_тестов():
    """Положительный контроль наличия общего счётчика отчёта."""
    совпадение = re.search(
        r"332 total tests\s*\((\d+) pass,\s*(\d+) skip\)", _текст(), re.I
    )
    if not совпадение:
        raise AssertionError("контроль общей регрессии не найден")
    пройдено, пропущено = map(float, совпадение.groups())
    return {"пройдено": пройдено, "пропущено": пропущено, "всего": пройдено + пропущено}


def _подстановка():
    """Отрицательная подстановка отличается по RDF-компоненту."""
    эт = эталон()
    эт["rdf_правильные"] = 23.0
    return эт


def _инвентарь_рецепта():
    """Машинно проверить обязательные входы независимого benchmark."""
    текст = _текст().lower()
    поля = {
        "исходные векторы": bool(re.search(r"raw vectors|исходн(?:ые|ых) вектор", текст)),
        "исходные запросы": bool(re.search(r"raw queries|исходн(?:ые|ых) запрос", текст)),
        "полная разметка": bool(re.search(r"ground[- ]truth|истинн(?:ые|ых) сосед", текст)),
        "контрольная сумма входов": bool(re.search(r"checksum|контрольн(?:ая|ой) сумм", текст)),
        "начальное состояние": bool(re.search(r"\bseed\b|начальн(?:ое|ого) состояни", текст)),
        "версия реализации": bool(re.search(r"commit|верси[яи] реализации", текст)),
        "независимый повтор": bool(re.search(r"independent replay|independent run|независим(?:ый|ая) повтор", текст)),
    }
    поля["рецепт_полон"] = all(поля.values())
    поля["отсутствует"] = [
        имя for имя, есть in поля.items()
        if имя not in {"рецепт_полон", "отсутствует"} and not есть
    ]
    return поля


def _код_причины():
    return "" if _инвентарь_рецепта()["рецепт_полон"] else "metrics_incommensurable"


def _самопроверка():
    наблюд = наблюдение()
    эт = эталон()
    алт = эталон_альт()
    assert наблюд["rdf_правильные"] == 24.0 and наблюд["многошаговый_всего"] == 4.0
    assert эт["rdf_правильные"] == 24.0 and эт["суперпозиция_правильные"] == 6.0
    assert эт["полнота_рецепта"] == 1.0
    assert алт["rdf_правильные"] == эт["rdf_правильные"]
    assert алт["полнота_рецепта"] == 1.0
    assert _подстановка() != наблюд
    assert _общий_счётчик_тестов()["пройдено"] == 328.0
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["рецепт_полон"]
    assert "исходные векторы" in инвентарь["отсутствует"]
    assert "независимый повтор" in инвентарь["отсутствует"]
    assert _код_причины() == "metrics_incommensurable"


_самопроверка()

