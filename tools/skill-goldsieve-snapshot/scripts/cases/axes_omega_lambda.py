# Внешнее измерение: Planck 2018, TT,TE,EE+lowE+lensing.
# https://arxiv.org/abs/1807.06209
OMEGA_L = 0.6889
OMEGA_L_SIGMA = 0.0056
REL_BAND = OMEGA_L_SIGMA / OMEGA_L          # относительная полоса ≈ 0,81 %

# Значение формулы при наиболее благоприятной для корпуса трактовке γ:
# γ = постоянная Эйлера-Маскерони 0,5772157 (вторая трактовка γ = φ⁻³ даёт
# расхождение ещё больше, поэтому берётся благоприятная — расхождение есть
# НИЖНЯЯ оценка).
GAMMA_EULER = 0.5772156649015329
FORMULA = GAMMA_EULER ** 8 * math.pi ** 4 / PHI ** 2


def _sigma_deviation():
    """Отклонение формулы от измерения Planck в сигмах измерения."""
    return (FORMULA - OMEGA_L) / OMEGA_L_SIGMA


def _family_values():
    """Значения семейства в окрестности цели: там, где попадания и возможны.

    Берётся не весь перебор, а окно ±0,7 декады вокруг цели: члены за окном не
    могут попасть в полосу, и включать их в оценку доли независимых нечестно —
    это разбавило бы плотность и завысило M_eff.
    """
    vals = F.enumerate_family(ACTUAL_RANGES)
    low, high = OMEGA_L / 5.0, OMEGA_L * 5.0
    return [v for v in vals if low <= v <= high]


def _meff_spec():
    return {
        "values": _family_values(),
        "eps": REL_BAND,
        "sigma": abs(_sigma_deviation()),
        "search_size": 123201,
    }


def _algebraic_spec():
    """Линейная форма для цели Planck.

    Формула содержит π (m = 4), поэтому граница бейкеровского типа к ней
    неприменима — это объявляется, а не обходится. PSLQ-детектор применим
    всегда: он проверяет, не воспроизводится ли само измеренное значение
    семейством при малых коэффициентах.
    """
    return {
        "target": OMEGA_L,
        "coeffs": (1, 0, 4, -2, 0),
        "has_pi": True,
        "rel_deviation": abs(FORMULA - OMEGA_L) / OMEGA_L,
        "max_coeff": 9,
        "free_coeff_limit": 6,
    }


def _algebraic_spec_no_pi():
    """Подсемейство без π: здесь граница бейкеровского типа — теорема.

    Ближайший к цели член подсемейства n·3^k·φ^p·e^q (m = 0) сравнивается с
    измерением, и вопрос ставится так: запрещает ли теория такую близость.
    Ожидаемый честный ответ — нет, граница астрономически слаба, то есть ось
    перебора теоремой не заменяется.
    """
    best = None
    for n in range(1, 10):
        for k in range(-4, 5):
            for p in range(-4, 5):
                for q in range(-3, 4):
                    v = n * 3.0 ** k * PHI ** p * math.e ** q
                    d = abs(v - OMEGA_L) / OMEGA_L
                    if best is None or d < best[0]:
                        best = (d, (n, k, 0, p, q))
    return {
        "target": OMEGA_L,
        "coeffs": best[1],
        "has_pi": False,
        "rel_deviation": best[0],
        "max_coeff": 9,
        "free_coeff_limit": 6,
    }


def _external():
    return {"value": OMEGA_L, "uncertainty": OMEGA_L_SIGMA,
            "source": "Planck 2018, https://arxiv.org/abs/1807.06209"}


def _multiplicity():
    size = 123201
