"""Трёхосный разбор совпадения формулы с Ω_Λ: сигмы, попытки, алгебра.

Луп 8 закрыл утверждение «формула γ⁸π⁴/φ² предсказывает Ω_Λ» вердиктом ПУСТО:
отклонение −41,1 сигма при выведенном пороге 5,06 сигма, но ось множественности
дала 113 ожидаемых случайных попаданий. Оставались два незакрытых допущения:

1. Порог 5,06 сигма выведен по Шидаку при ПРЕДПОЛОЖЕНИИ независимости 123 201
   перебранных формул. Члены семейства лежат на логарифмической решётке и
   независимыми не являются. Сито С20 проверяет, меняется ли вывод при законной
   замене числа попыток на эффективное.
2. Не является ли близость запрещённой или, наоборот, бесплатной по теории
   линейных форм в логарифмах. Сито С21: PSLQ-детектор плюс граница
   бейкеровского типа.

Оси НЕ сливаются в одно число: доказанной формулы, которая сводит сигмы,
поправку на множественность и биты описания к единому вердикту без
произвольного параметра, не существует — байесовский Occam-фактор имеет
контрпримеры (Belot), множественность входит только через приор (Scott &
Berger), а многокритериальный выбор даёт лишь множество Парето. Поэтому каждая
ось остаётся отдельной координатой, а правило приоритетов между ними — часть
рецепта и попадает в отпечаток.
"""

import math
