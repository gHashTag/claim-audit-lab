def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("реестр Sacred Predictions отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def наблюдение():
    """Разобрать только строки текущей таблицы прогнозов."""
    строки = []
    for строка in _текст().splitlines():
        совпадение = re.match(r"^\|\s*\*\*(\d{3})\*\*\s*\|(.+)$", строка)
        if not совпадение:
            continue
        ячейки = [часть.strip() for часть in совпадение.group(2).strip().strip("|").split("|")]
        if len(ячейки) < 5:
            continue
        строки.append({"id": совпадение.group(1), "статус": ячейки[3], "формула": ячейки[4]})
    if not строки:
        raise AssertionError("таблица прогнозов не найдена")
    return {
        "число": float(len(строки)),
        "ожидающие": float(sum(x["статус"] == "PENDING" for x in строки)),
    }


def эталон():
    """Вычисляемый эталон из подробных секций, а не из таблицы."""
    ids = re.findall(r"^###\s+(\d{3}):\s+", _текст(), re.M)
    if not ids:
        raise AssertionError("подробные секции прогнозов не найдены")
    return {"число": float(len(ids)), "ожидающие": float(len(ids))}


def эталон_alt():
    """Второй принцип: посчитать формульные карточки и их идентификаторы."""
    текст = _текст()
    карточки = re.findall(r"^###\s+(\d{3}):.*?^\*\*Formula:\*\*", текст, re.M | re.S)
    # Второй путь видит формульные карточки, но не может подтвердить статус
    # публикации: это принципиально другой observable, который должен выявить
    # недостающий независимый журнал, а не повторить таблицу.
    return {"число": float(len(карточки)), "ожидающие": 0.0}


def _положительный_контроль():
    """Контрольный путь: у каждой карточки есть текущий экспериментальный статус."""
    текст = _текст()
    ids = re.findall(r"^###\s+(\d{3}):\s+", текст, re.M)
    статусы = re.findall(r"^\*\*Current Experimental Status:\*\*", текст, re.M)
    return {"число": float(len(статусы)), "ожидающие": float(len(статусы))}


def _подстановка():
    значение = наблюдение()
    return {"число": значение["число"] - 1.0,
            "ожидающие": max(0.0, значение["ожидающие"] - 1.0)}


def _доказательный_инвентарь():
    текст = _текст().lower()
    поля = {
        "дата создания": bool(re.search(r"\*\*created:\*\*\s+[^\n]+", текст)),
        "временная метка": bool(re.search(r"unix:\s*\d+", текст)),
        "криптографический отпечаток": bool(re.search(r"sha-?256|hash|хеш|подписан", текст)),
        "сырой журнал проверки": bool(re.search(r"verification log|журнал проверки|audit log", текст)),
        "независимый повтор": bool(re.search(r"independent replay|independent verification|независим(?:ый|ая) повтор", текст)),
        "внешняя ссылка на каждую цель": len(
            re.findall(r"doi|arxiv|https?://", текст)
        ) >= 7,
    }
    поля["рецепт_полон"] = all(поля.values())
    поля["отсутствует"] = [имя for имя, есть in поля.items()
                           if имя not in {"рецепт_полон", "отсутствует"} and not есть]
    return поля


def _код_причины():
    return "" if _доказательный_инвентарь()["рецепт_полон"] else "metrics_incommensurable"


def _самопроверка():
    наблюдаемое = наблюдение()
    эталонное = эталон()
    альтернативное = эталон_alt()
    assert наблюдаемое["число"] == 7.0
    assert эталонное["число"] == 7.0
    assert альтернативное["число"] == 7.0
    assert наблюдаемое["ожидающие"] == эталонное["ожидающие"]
    assert альтернативное["число"] == 7.0
    assert альтернативное["ожидающие"] == 0.0
    assert альтернативное != эталонное
    assert _положительный_контроль()["число"] == 7
    инвентарь = _доказательный_инвентарь()
    assert not инвентарь["рецепт_полон"]
    assert set(инвентарь["отсутствует"]) == {
        "криптографический отпечаток", "сырой журнал проверки",
        "независимый повтор", "внешняя ссылка на каждую цель",
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _подстановка() != наблюдаемое
    assert _положительный_контроль() == эталонное


_самопроверка()

