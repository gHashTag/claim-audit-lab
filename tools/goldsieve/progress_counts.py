#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Разбор чисел, напечатанных словами в старых машинных отчётах.

Модуль не восстанавливает значения: он принимает только число, присутствующее
в самом тексте отчёта. Отдельный словарь делает допустимые формы явными и
исключает неоднозначное угадывание по соседним тикам.
"""

from __future__ import annotations


RU_COUNT_WORDS = {
    "ноль": 0, "один": 1, "одна": 1, "два": 2, "две": 2,
    "двух": 2, "три": 3, "трёх": 3, "четыре": 4, "четырёх": 4,
    "пять": 5, "пяти": 5, "шесть": 6, "шести": 6, "семь": 7,
    "семи": 7, "восемь": 8, "восьми": 8, "девять": 9, "десять": 10,
}


def count_token(token: str) -> int | None:
    """Преобразовать наблюдаемый арабский или русский счётчик."""
    token = token.strip().lower()
    if token.isdigit():
        return int(token)
    return RU_COUNT_WORDS.get(token)
