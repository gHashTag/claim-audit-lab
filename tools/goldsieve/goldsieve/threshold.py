"""Порог разрешающей способности семейства формул.

Смысл. Если семейство содержит M выражений, разбросанных по D декадам, то
случайная цель почти всегда оказывается рядом с каким-нибудь его членом.
Совпадение начинает что-то означать только тогда, когда оно точнее порога, при
котором ожидаемое число случайных попаданий падает до единицы.

Вывод (для приблизительно логарифмически равномерного семейства). Доля членов,
попадающих в относительную полосу +-eps вокруг цели, равна ширине полосы в
логарифмической мере, делённой на размах порядков:

    E[h](eps) = M * (2*eps/ln 10) / D

Приравнивая E[h] = 1, получаем порог

    eps* = ln 10 * D / (2 M)

Это не эвристика: единственное допущение — логарифмическая равномерность, и
именно оно проверяется здесь Монте-Карло. Величина, обратная M, объясняет,
почему честность вывода про «согласие с точностью 0,001 %» целиком зависит от
того, сколько формул реально перебрано, а не от того, сколько объявлено.

Все функции этого модуля покрыты самопроверкой в конце файла, включая guard на
подставленный неверный ответ, поставленный там, где он реально отличается.
"""

import math

from . import family

# диапазон порядков, по которому раскладываются цели корпуса
DECADES = (-6.0, 24.0)

DECLARED_RANGES = family.STANDARD_RANGES
ACTUAL_RANGES = {"n": range(1, 10), "k": range(-6, 7), "m": range(-4, 5),
                 "p": range(-6, 7), "q": range(-4, 5)}


def analytic_threshold(size, decades):
    """eps* = ln10 * D / (2 M) — замкнутая формула порога.

    size: число выражений в семействе; decades: размах порядков целей.
    """
    if size <= 0:
        raise ValueError("размер семейства должен быть положительным")
    if decades <= 0:
        raise ValueError("размах порядков должен быть положительным")
    return math.log(10.0) * decades / (2.0 * size)


def expected_hits_analytic(eps, ranges, decades=DECADES):
    """Ожидаемое число случайных попаданий в полосу +-eps.

    Считается по фактически перечисленному семейству, а не по формуле, чтобы
    расчёт не зависел от допущения о равномерности там, где его можно избежать.
    """
    values = family.enumerate_family(ranges)
    lo, hi = decades
    inside = [v for v in values if 10.0 ** lo <= v <= 10.0 ** hi]
    band = 2.0 * eps / math.log(10.0)
    return len(inside) * band / (hi - lo)


def crossover(ranges, empirical=False, trials=400, decades=DECADES, seed=5):
    """Двоичный поиск eps, при котором ожидаемое число попаданий равно 1."""
    lo, hi = 1e-12, 1e-1
    for _ in range(60):
        mid = math.sqrt(lo * hi)
        if empirical:
            _, e = family.empirical_multiplicity(decades, mid, ranges=ranges,
                                                 trials=trials, seed=seed)
        else:
            e = expected_hits_analytic(mid, ranges, decades)
        if e < 1.0:
            lo = mid
        else:
            hi = mid
    return math.sqrt(lo * hi)


# --------------------------------------------------------------------------
# локальный порог: без свободного параметра
# --------------------------------------------------------------------------
#
# Найденный дефект замкнутой формулы. Величина eps* = ln10*D/(2M) содержит
# размах порядков D, который выбирает человек. Для целей корпуса разумны и D=5,
# и D=30, а порог отличается при этом в шесть раз — значит по одной этой
# формуле можно получить любой удобный вывод. Такой порог нельзя предъявлять
# как результат.
#
# Порог, свободный от произвола: считать плотность семейства ЛОКАЛЬНО вокруг
# самой цели. Ожидаемое число попаданий в полосу +-eps вокруг V равно числу
# членов семейства в интервале [V(1-eps), V(1+eps)], и это число просто
# пересчитывается перечислением. Ничего выбирать не нужно.


def local_hits(target, eps, ranges, values=None):
    """Сколько членов семейства попадают в полосу +-eps вокруг цели."""
    if values is None:
        values = family.enumerate_family(ranges)
    lo, hi = abs(target) * (1.0 - eps), abs(target) * (1.0 + eps)
    return sum(1 for v in values if lo <= v <= hi)


def local_density(target, ranges, values=None, window_decades=1.0):
    """Плотность семейства вокруг цели: членов на одну декаду.

    Прямой счёт попаданий не годится как порог: число попаданий целочисленно и
    скачет ступеньками (в семействе много совпадающих значений), поэтому
    «ровно одно попадание» для одних целей недостижимо, а для других
    достигается сразу тройкой. Плотность в окне такой ступенчатости не имеет.

    Ширина окна — единственный оставшийся параметр, и в отличие от глобального
    D он не произволен: плотность локально гладкая, поэтому порог почти не
    зависит от ширины. Это проверяется в самопроверке.
    """
    if values is None:
        values = family.enumerate_family(ranges)
    c = math.log10(abs(target))
    lo, hi = 10.0 ** (c - window_decades), 10.0 ** (c + window_decades)
    n = sum(1 for v in values if lo <= v <= hi)
    return n / (2.0 * window_decades)


def local_threshold(target, ranges, values=None, window_decades=1.0):
    """Порог eps, при котором ожидаемое число попаданий вокруг цели равно 1.

    E[h](eps) = плотность * 2*eps/ln10 = 1  =>  eps = ln10 / (2 * плотность).

    Свободного глобального размаха декад здесь нет: используется плотность
    именно вокруг данной цели.
    """
    d = local_density(target, ranges, values, window_decades)
    if d <= 0.0:
        return float("inf")     # семейство не достаёт до цели вообще
    return math.log(10.0) / (2.0 * d)


def coincidence_is_free(target, eps_observed, ranges, values=None):
    """True, если совпадение точности eps_observed вокруг цели бесплатно."""
    return eps_observed >= local_threshold(target, ranges, values)


# --------------------------------------------------------------------------
# самопроверка
# --------------------------------------------------------------------------

def selftest():
    """9 проверок. Возвращает число провалов."""
    fail = 0

    def check(name, cond):
        nonlocal fail
        if cond:
            print("  ok   %s" % name)
        else:
            fail += 1
            print("  FAIL %s" % name)

    # 1. Формула согласуется с прямым перечислением семейства.
    # Берём eps* по формуле и проверяем, что перечисление даёт около одного
    # попадания. Это проверка допущения о логарифмической равномерности.
    size = len(family.enumerate_family(ACTUAL_RANGES))
    eps = analytic_threshold(size, DECADES[1] - DECADES[0])
    hits = expected_hits_analytic(eps, ACTUAL_RANGES)
    check("формула порога согласуется с перечислением (E[h]=%.3f)" % hits,
          0.5 <= hits <= 2.0)

    # 2. ПОДСТАВКА: неверный порог, завышенный в 10 раз, обязан провалить ту же
    # проверку. Без этого guard пункт 1 прошёл бы при почти любой формуле.
    bad = eps * 10.0
    bad_hits = expected_hits_analytic(bad, ACTUAL_RANGES)
    check("подставной порог x10 отвергнут (E[h]=%.2f)" % bad_hits,
          not (0.5 <= bad_hits <= 2.0))

    # 3. ПОДСТАВКА: порог, заниженный в 10 раз, тоже обязан провалиться.
    bad2 = eps / 10.0
    bad2_hits = expected_hits_analytic(bad2, ACTUAL_RANGES)
    check("подставной порог /10 отвергнут (E[h]=%.3f)" % bad2_hits,
          not (0.5 <= bad2_hits <= 2.0))

    # 4. Аналитика против двоичного поиска по перечислению: расхождение мало.
    num = crossover(ACTUAL_RANGES)
    rel = abs(num - eps) / eps
    check("двоичный поиск воспроизводит формулу (расхождение %.1f %%)"
          % (rel * 100.0), rel < 0.05)

    # 5. Порог обратно пропорционален размеру: удвоение перебора вдвое ужимает
    # порог. Свойство прямо следует из вывода и легко ломается при опечатке.
    a = analytic_threshold(1000, 5.0)
    b = analytic_threshold(2000, 5.0)
    check("порог обратно пропорционален размеру перебора",
          abs(a / b - 2.0) < 1e-12)

    # 6. Замкнутая формула зависит от произвольного D: это её ЗАФИКСИРОВАННЫЙ
    # дефект, а не случайность. Проверка требует, чтобы расхождение между
    # разумными выборами D было большим — иначе кто-то «починит» формулу,
    # подобрав D, и разница молча исчезнет.
    t5 = analytic_threshold(size, 5.0)
    t30 = analytic_threshold(size, 30.0)
    check("зависимость от выбора D зафиксирована (%.2g против %.2g, x%.0f)"
          % (t5, t30, t30 / t5), t30 / t5 > 3.0)

    # 7. Локальный порог устойчив к ширине окна: втрое разное окно меняет
    # порог менее чем на треть. Именно это отличает его от произвольного D,
    # который менял результат в шесть раз.
    values = family.enumerate_family(ACTUAL_RANGES)
    target = 1836.152673426       # m_p/m_e, CODATA 2022
    lt = local_threshold(target, ACTUAL_RANGES, values)
    narrow = local_threshold(target, ACTUAL_RANGES, values, 0.5)
    wide = local_threshold(target, ACTUAL_RANGES, values, 1.5)
    spread = max(narrow, wide) / min(narrow, wide)
    check("локальный порог устойчив к ширине окна (разброс x%.2f)" % spread,
          spread < 1.35)

    # 8. ПОДСТАВКА: если бы плотность считалась с ошибкой в 10 раз, порог тоже
    # ушёл бы в 10 раз — проверка обязана это увидеть. Guard нужен, потому что
    # пункт 7 сам по себе прошёл бы при любой систематически смещённой
    # плотности.
    d_true = local_density(target, ACTUAL_RANGES, values)
    bad_thr = math.log(10.0) / (2.0 * d_true * 10.0)
    check("подставная плотность x10 отвергнута (%.2g против %.2g)"
          % (bad_thr, lt), abs(bad_thr / lt - 1.0) > 0.5)

    # 9. Предикат на реальных числах корпуса: заявленная точность 0,01 %
    # вокруг m_p/m_e бесплатна, а точность измерения CODATA (1,7e-11) — нет.
    free = coincidence_is_free(target, 1e-4, ACTUAL_RANGES, values)
    not_free = coincidence_is_free(target, 1.7e-11, ACTUAL_RANGES, values)
    check("0,01 %% бесплатно, 1,7e-11 нет (локальный порог %.2g)" % lt,
          free and not not_free)

    return fail


if __name__ == "__main__":
    raise SystemExit(1 if selftest() else 0)
