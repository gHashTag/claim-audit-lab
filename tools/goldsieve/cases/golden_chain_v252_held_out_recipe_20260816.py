from goldsieve.sieve import Claim

ИСТОЧНИК = "/home/user/workspace/corpus/trinity/deploy/trinity-nexus/docs/research/trinity-golden-chain-v2-52-held-out-report.md"
if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться без регистрации в sys.modules")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Golden Chain v2.52 отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def наблюдение():
    совпадение = re.search(
        r"\s*KN 4-gram\s+\|\s+([0-9.]+)\s+\|\s+([0-9.]+)\s+\|\s+1\.0x\s*",
        _текст())
    if not совпадение:
        raise AssertionError("PPL чётных чанков не найден")
    значение = float(совпадение.group(2))
    if значение != 1.85:
        raise AssertionError("PPL чётных чанков изменился")
    return значение


def _контроль():
    совпадение = re.search(r"Context crosses eval/train:\s+(\d+) \(([0-9.]+)%\)", _текст())
    if not совпадение:
        raise AssertionError("контроль пересечения контекстов не найден")
    количество, процент = совпадение.groups()
    return float(процент)


def _эталон_контроля_из_сырых_счётчиков():
    совпадение = re.search(r"Context crosses eval/train:\s+(\d+) \(([0-9.]+)%\)", _текст())
    размер = re.search(r"2497 4-gram evals", _текст())
    if not совпадение or not размер:
        raise AssertionError("счётчики контроля не найдены")
    количество = int(совпадение.group(1))
    всего = 2497
    return количество / всего * 100.0


def _инвентарь_рецепта():
    текст = _текст().lower()
    поля = {
        "исходные тексты train и eval": bool(re.search(r"separate text corpora|hamlet|macbeth|раздельн(?:ые|ых) корпус", текст)),
        "точная реализация": bool(re.search(r"commit sha|git commit|git sha|точн(?:ая|ый) версия кода", текст)),
        "полный исходный код запуска": bool(re.search(r"src/minimal_forward\.zig", текст)) and bool(re.search(r"source code|исходн(?:ый|ого) код", текст)),
        "контрольная сумма входа": bool(re.search(r"sha256|checksum|input hash|контрольная сумма", текст)),
        "точные границы разбиения": bool(re.search(r"train 3992 tokens, eval 999 tokens", текст)),
        "независимый повтор": bool(re.search(r"independent replay|independent run|independent reproduction|независим(?:ый|ая) повтор", текст)),
        "параметры сглаживания и оценки": bool(re.search(r"kn d=0\.25|smoothing.*d=0\.25|усредн", текст)),
        "рецепт_полон": False,
    }
    поля["рецепт_полон"] = all(поля[имя] for имя in поля if имя != "рецепт_полон")
    поля["отсутствует"] = [имя for имя, есть in поля.items()
                           if имя not in {"рецепт_полон", "отсутствует"} and not есть]
    return поля


def _код_причины():
    return "" if _инвентарь_рецепта()["рецепт_полон"] else "metrics_incommensurable"


def _неверный_ответ():
    return 2.42


def _самопроверка():
    assert наблюдение() == 1.85
    assert _контроль() == 99.0
    assert abs(_эталон_контроля_из_сырых_счётчиков() - 99.0) < 0.1
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["рецепт_полон"]
    assert set(инвентарь["отсутствует"]) == {
        "точная реализация", "полный исходный код запуска", "контрольная сумма входа", "независимый повтор",
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _неверный_ответ() != наблюдение()
    assert _контроль() != наблюдение()


_самопроверка()

