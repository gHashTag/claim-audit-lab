"""Заявленная вероятность случайного попадания в класс EXACT.

Корпус в разделе Statistical Significance таблицей утверждает: для класса
EXACT (относительная ошибка меньше 0,01 %) вероятность случайного совпадения
составляет «1 из 500 (0,2 %)», наблюдается «1 из 35 (2,9 %)», и это даёт
значимость «около 10 сигм».

Проверяется именно эта вероятность 0,2 %, а не итоговое число сигм: если
вероятность занижена, значимость рушится автоматически.

Вычисляемый эталон. Для каждой цели вероятность того, что хотя бы один член
семейства попадёт в относительную полосу +-1e-4, равна отношению ширины полосы
к среднему расстоянию между членами семейства вблизи этой цели, то есть
1e-4 / eps_local, где eps_local — локальный порог из goldsieve.threshold
(ограниченная единицей). Средняя по фактическим целям корпуса вероятность и
есть эталон. Никакой цитаты не используется: плотность считается перечислением
семейства.

Ожидание корпуса и расчёт расходятся не на проценты, а в сотни раз, поэтому
проверка разрешающая: подставка отличается заведомо.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from goldsieve import family                                    # noqa: E402
from goldsieve.sieve import Claim                               # noqa: E402
from goldsieve.threshold import local_threshold, ACTUAL_RANGES  # noqa: E402

SOURCE = ("/home/user/workspace/corpus/trinity/docs/docs/"
          "math-foundations/sacred-formulas.md")

EXACT_TOLERANCE = 1e-4      # класс EXACT: ошибка меньше 0,01 %
STATED_PROBABILITY = 0.002  # «1 из 500», как написано в корпусе

_cache = {}


def _targets():
    """Цели из таблиц корпуса: те строки, где указана относительная ошибка."""
    if "t" in _cache:
        return _cache["t"]
    out = []
    for ln in open(SOURCE).read().split("\n"):
        if not ln.startswith("|"):
            continue
        cells = [c.strip() for c in ln.strip("|").split("|")]
        if len(cells) < 5:
            continue
        if not re.search(r"\*{0,2}([\d.]+)\s*%\*{0,2}$", cells[-1]):
            continue
        raw = cells[1].replace(",", "").replace("$", "").strip()
        try:
            v = float(raw)
        except ValueError:
            continue
        if v != 0.0:
            out.append(v)
    _cache["t"] = out
    return out


def _values():
    if "v" not in _cache:
        _cache["v"] = family.enumerate_family(ACTUAL_RANGES)
    return _cache["v"]


def reference_probability():
    """Средняя вероятность случайного попадания в класс EXACT.

    Считается перечислением семейства вокруг каждой фактической цели корпуса.
    """
    vals = _values()
    ps = []
    for t in _targets():
        thr = local_threshold(t, ACTUAL_RANGES, vals)
        ps.append(min(1.0, EXACT_TOLERANCE / thr))
    return sum(ps) / len(ps)


def observed_probability():
    """Вероятность, как её объявляет корпус."""
    return STATED_PROBABILITY


# Заведомо неверные ответы, поставленные там, где они реально отличаются.
# Вероятность лежит в [0, 1], поэтому подставки берутся внутри отрезка: если
# сито их пропустит, значит оно не различает ничего.

def wrong_as_stated():
    return STATED_PROBABILITY      # ровно то, что пишет корпус


def wrong_five_percent():
    return 0.05


def wrong_half():
    return 0.5


def null_probability():
    """Позитивный контроль: перебор, при котором вероятность обязана стать 0,2 %.

    Первая попытка контроля прореживала семейство в 500 раз и провалилась: сито
    С5 честно сообщило, что контроль не воспроизводит эталон. Причина в том, что
    прореживание отсортированного списка меняет плотность неравномерно по
    порядкам, и «в 500 раз меньше членов» не означает «в 500 раз ниже локальная
    плотность у каждой цели».

    Вторая попытка тоже была неверной по роли: она воспроизводила ЗАЯВЛЕННОЕ
    значение, а позитивный контроль обязан воспроизводить ЭТАЛОН. Сито С5
    сорвало и её — и правильно, потому что контроль, дающий не эталон, ничего не
    подтверждает о конвейере.

    Верный позитивный контроль: та же вероятность, но посчитанная другим путём —
    через среднюю фактическую плотность членов семейства на декаду, а не через
    локальный порог каждой цели. Если конвейер цел, оба пути дают эталон. Если
    сломан, они разойдутся.
    """
    import math
    density = density_of_targets()
    thr = math.log(10.0) / (2.0 * density)
    return min(1.0, EXACT_TOLERANCE / thr)


def density_of_targets():
    """Фактическая плотность семейства вокруг целей: членов на декаду.

    Приводится как отдельная величина, потому что именно она отвечает за
    расхождение: у корпуса она неявно предполагается равной 23, а фактически
    измеряется перечислением.
    """
    import math
    vals = _values()
    ds = []
    for t in _targets():
        thr = local_threshold(t, ACTUAL_RANGES, vals)
        ds.append(math.log(10.0) / (2.0 * thr))
    return sum(ds) / len(ds)


def sample():
    """Повероятности по каждой цели: нужны для статистики и разброса."""
    vals = _values()
    return [min(1.0, EXACT_TOLERANCE / local_threshold(t, ACTUAL_RANGES, vals))
            for t in _targets()]


