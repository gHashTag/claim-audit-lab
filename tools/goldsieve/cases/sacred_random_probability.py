CLAIMS = [
    Claim(
        name=("Вероятность случайного попадания в класс EXACT равна "
              "1 из 500 (0,2 %)"),
        stated=STATED_PROBABILITY,
        reference=reference_probability,
        observed=observed_probability,
        wrong=[wrong_as_stated, wrong_five_percent, wrong_half],
        null_model=null_probability,
        null_kind="positive",
        # Выборка намеренно НЕ передаётся. Заявление корпуса — одно число из
        # текста, выборки за ним нет; а если подать сюда разброс расчётных
        # вероятностей по целям, то сито С10 начнёт сравнивать эталон сам с
        # собой, пройдёт, и смягчит итоговый вердикт с опровержения до вопроса.
        # Это наблюдение занесено в ведомость как открытый вопрос к своду
        # вердиктов: PASS у С10 не должен смягчать опровержение, если С10
        # сравнивал не заявленную величину.
        # допуск 20 % от эталона: расхождение в сотни раз различается с запасом
        tolerance=0.2,
        inputs=[SOURCE],
        skip_reasons=COMMON,
        notes=("Разброс расчётной вероятности по целям корпуса: от %.3f до "
               "%.3f при средней %.3f. Проверяется вероятность, а не итоговое "
               "число сигм: значимость выводится из неё, поэтому ошибка в "
               "вероятности обрушивает и значимость."
               % (min(sample()), max(sample()), reference_probability())),
    ),
]
