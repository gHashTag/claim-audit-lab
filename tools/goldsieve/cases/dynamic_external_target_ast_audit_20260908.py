# -*- coding: utf-8 -*-
"""Машинный вопрос о шести динамических внешних целях.

Кейс читает AST файлов cases/*.py и не импортирует сами кейсы. В шести
словарях внешних целей значение или неопределённость вычисляются выражением,
поэтому независимый текстовый маршрут не может предъявить числовой вход для
сверки. Это вопрос о читаемости входа, а не научное подтверждение или
опровержение любой внешней величины.
"""

from __future__ import annotations

import ast
from pathlib import Path

from goldsieve.sieve import Claim


КОРЕНЬ = Path(__file__).resolve().parent.parent
КЕЙСЫ = КОРЕНЬ / "cases"
КОД_ВОПРОСА = "no_computable_reference"


def _текст(узел: ast.AST) -> str:
    """Сохранить выражение цели в стабильной форме без его исполнения."""
    return ast.unparse(узел)


def _динамические_цели() -> list[dict]:
    """Найти словари value/uncertainty с не-литеральными полями."""
    найденные: list[dict] = []
    for путь in sorted(КЕЙСЫ.glob("*.py")):
        if путь.name == Path(__file__).name:
            continue
        дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.Dict):
                continue
            ключи = [
                ключ.value if isinstance(ключ, ast.Constant) else None
                for ключ in узел.keys
            ]
            if "value" not in ключи or "uncertainty" not in ключи:
                continue
            поля = {
                ключ: значение
                for ключ, значение in zip(ключи, узел.values)
                if ключ is not None
            }
            динамические = []
            for имя in ("value", "uncertainty"):
                выражение = поля[имя]
                try:
                    ast.literal_eval(выражение)
                except (ValueError, SyntaxError):
                    динамические.append(
                        {"поле": имя, "выражение": _текст(выражение)}
                    )
            if динамические:
                найденные.append(
                    {
                        "файл": путь.name,
                        "строка": узел.lineno,
                        "динамические_поля": динамические,
                    }
                )
    return найденные


def _наблюдаемое() -> dict:
    цели = _динамические_цели()
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
        "число_нечитаемых_целей": len(цели),
        "цели": цели,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["число_нечитаемых_целей"] += 1
    return результат


def _контроль() -> float:
    return float(len(_динамические_цели()))


