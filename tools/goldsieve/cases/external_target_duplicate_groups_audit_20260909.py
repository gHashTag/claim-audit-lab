# -*- coding: utf-8 -*-
"""Машинный вопрос о слиянии повторных внешних целей.

Кейс самостоятельно разбирает AST файлов cases/*.py и собирает только
литеральные словари с числом, погрешностью и узлом источника. Отпечаток
строится из округлённых величины, погрешности и узла источника, а не из имени
файла. Поэтому семь групп повторов и пятнадцать записей можно предъявить
независимо от отчёта сторожа новизны. Повтор цели не является новым научным
измерением: нужен единый реестр и решение о слиянии.
"""

from __future__ import annotations

import ast
import math
from pathlib import Path
from urllib.parse import urlparse

from goldsieve.sieve import Claim


КАТАЛОГ = Path(__file__).resolve().parent
ИМЯ_КЕЙСА = Path(__file__).name
КОД_ВОПРОСА = "duplicate_external_target_groups"
ОЖИДАЕМЫЕ_ГРУППЫ = 7
ОЖИДАЕМЫЕ_ЗАПИСИ = 15


def _литерал(узел: ast.AST):
    try:
        return ast.literal_eval(узел)
    except (ValueError, SyntaxError, TypeError):
        return None


def _узел_источника(источник: object) -> str:
    try:
        узел = urlparse(str(источник)).netloc.lower()
    except ValueError:
        узел = ""
    return узел[4:] if узел.startswith("www.") else узел


def _свернуть(значение: float) -> str:
    if значение == 0.0:
        return "0"
    порядок = math.floor(math.log10(abs(значение)))
    мантисса = значение / (10.0 ** порядок)
    округлённая = round(мантисса / 1.0e-6) * 1.0e-6
    return "%.6fe%d" % (округлённая, порядок)


def _отпечаток(узел: ast.Dict) -> str | None:
    ключи = [_литерал(ключ) for ключ in узел.keys]
    значения = {
        ключ: _литерал(значение)
        for ключ, значение in zip(ключи, узел.values)
        if ключ is not None
    }
    if not {"value", "uncertainty", "source"}.issubset(значения):
        return None
    величина = значения["value"]
    погрешность = значения["uncertainty"]
    источник = значения["source"]
    if isinstance(величина, bool) or not isinstance(величина, (int, float)):
        return None
    if isinstance(погрешность, bool) or not isinstance(погрешность, (int, float)):
        return None
    if not isinstance(источник, str):
        return None
    return "%s|%s|%s" % (
        _свернуть(float(величина)),
        _свернуть(float(погрешность)),
        _узел_источника(источник),
    )


def _прочитать() -> dict[str, list[str]]:
    группы: dict[str, list[str]] = {}
    for путь in sorted(КАТАЛОГ.glob("*.py")):
        if путь.name == ИМЯ_КЕЙСА:
            continue
        дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.Dict):
                continue
            отпечаток = _отпечаток(узел)
            if отпечаток is not None:
                группы.setdefault(отпечаток, []).append(путь.name)
    return группы


def _наблюдаемое() -> dict:
    группы = _прочитать()
    повторы = {
        ключ: sorted(set(значения))
        for ключ, значения in группы.items()
        if len(set(значения)) > 1
    }
    записи = sum(len(значения) for значения in повторы.values())
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
        "группы_повторов": len(повторы),
        "повторяющиеся_записи": записи,
        "повторы": повторы,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["группы_повторов"] += 1
    return результат


def _контроль() -> float:
    return float(_наблюдаемое()["повторяющиеся_записи"])


def _самопроверка() -> None:
    результат = _наблюдаемое()
    assert результат["группы_повторов"] == ОЖИДАЕМЫЕ_ГРУППЫ
    assert результат["повторяющиеся_записи"] == ОЖИДАЕМЫЕ_ЗАПИСИ
    assert len(результат["повторы"]) == ОЖИДАЕМЫЕ_ГРУППЫ
    assert _ложное_наблюдаемое()["группы_повторов"] != результат["группы_повторов"]


_самопроверка()

