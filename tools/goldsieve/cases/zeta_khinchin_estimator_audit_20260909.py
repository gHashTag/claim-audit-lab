# -*- coding: utf-8 -*-
"""Машинный вопрос о неопределённом оценивателе числа Хинчина.

Кейс самостоятельно читает текстовый анализ Trinity. Наличие нескольких
контрольных строк ещё не выбирает оцениватель и число частичных дробей:
сам текст помечает эти параметры как неуказанные. Поэтому результатом
остаётся машинный ВОПРОС, а научный статус — not-evaluated.
"""

from __future__ import annotations

import re
from pathlib import Path

from goldsieve.sieve import Claim


if __name__ in __import__("sys").modules:
    raise RuntimeError(
        "кейс должен загружаться через module_from_spec без регистрации"
    )


КОРЕНЬ = Path(__file__).resolve().parent.parent
ИСТОЧНИК = (
    КОРЕНЬ.parent
    / "corpus"
    / "trinity"
    / "data"
    / "zeta"
    / "zeta_bin_analysis_update.md"
)
КОД_ВОПРОСА = "khinchin_estimator_undeclared"


def _текст() -> str:
    return ИСТОЧНИК.read_text(encoding="utf-8")


def _наблюдаемое() -> dict:
    текст = _текст()
    описание_неполно = (
        "the estimator is unspecified" in текст
        and "neither of which this document records" in текст
    )
    контрольные_строки = re.findall(
        r"^\|\s*(?:mean of per-expansion|pooled geometric mean).*?\|$",
        текст,
        flags=re.MULTILINE,
    )
    варианты_m = sorted(
        {
            int(значение)
            for значение in re.findall(r"m\s*=\s*(\d+)", текст)
        }
    )
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "оцениватель_и_число_членов_не_указаны": описание_неполно,
        "строк_контроля": len(контрольные_строки),
        "варианты_числа_членов": варианты_m,
        "код_вопроса": КОД_ВОПРОСА,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["оцениватель_и_число_членов_не_указаны"] = False
    результат["код_вопроса"] = ""
    return результат


def _контроль_формы() -> float:
    результат = _наблюдаемое()
    return float(
        bool(результат["оцениватель_и_число_членов_не_указаны"])
        + (результат["строк_контроля"] == 2)
    )


