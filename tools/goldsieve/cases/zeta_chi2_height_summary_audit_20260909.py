"""Машинный вопрос о согласованности высотной сводки χ²/dof.

Кейс независимо читает первую высотную таблицу корпуса и отдельный CSV
Figure 1. Оба входа называют величину χ²/dof, но предъявляют разные формы
разбиения высот и разные последовательности чисел. Это структурный вопрос о
воспроизводимости входа, а не новый внешний эталон и не утверждение о законе
GUE.
"""

from __future__ import annotations

import csv
from pathlib import Path

from goldsieve.sieve import Claim


КОРЕНЬ = Path(__file__).resolve().parent.parent
КОРПУС = (
    Path("/home/user/workspace/corpus/trinity/data/zeta")
    / "zeta_gue_analysis_results.md"
)
CSV_ВХОД = (
    Path("/home/user/workspace/corpus/trinity/data/zeta")
    / "zeta_figure1_chi2.csv"
)
КОД_ВОПРОСА = "chi2_height_summary_mismatch"


def _таблица_в_корпусе() -> list[dict]:
    текст = КОРПУС.read_text(encoding="utf-8")
    начало = текст.index("## Height Dependence")
    конец = текст.index("### Local Mean Spacing Validation", начало)
    строки = текст[начало:конец].splitlines()
    найденные = []
    for строка in строки:
        клетки = [клетка.strip() for клетка in строка.strip().strip("|").split("|")]
        if len(клетки) < 3:
            continue
        if клетки[0] in {"Height Range", "--------------"}:
            continue
        try:
            число = float(клетки[2])
        except ValueError:
            continue
        найденные.append({"высота": клетки[0], "chi2_dof": число})
    return найденные


def _csv_таблица() -> list[dict]:
    with CSV_ВХОД.open(newline="", encoding="utf-8") as файл:
        строки = list(csv.DictReader(файл))
    результат = []
    for строка in строки:
        результат.append(
            {
                "T_mid": float(строка["T_mid"]),
                "chi2_dof": float(строка["chi2_dof"]),
            }
        )
    return результат


def _наблюдаемое() -> dict:
    сводка = _таблица_в_корпусе()
    csv_строки = _csv_таблица()
    значения_сводки = [строка["chi2_dof"] for строка in сводка]
    значения_csv = [строка["chi2_dof"] for строка in csv_строки]
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
        "строк_в_сводке": len(сводка),
        "строк_в_csv": len(csv_строки),
        "значения_сводки": значения_сводки,
        "значения_csv": значения_csv,
        "последовательности_совпадают": значения_сводки == значения_csv,
        "первые_шесть_совпадают": значения_сводки == значения_csv[:6],
        "высотные_метки_сводки": [строка["высота"] for строка in сводка],
        "высоты_csv": [строка["T_mid"] for строка in csv_строки],
    }


def _неверный_ответ() -> dict:
    результат = _наблюдаемое()
    результат["последовательности_совпадают"] = True
    результат["первые_шесть_совпадают"] = True
    return результат


def _контроль() -> float:
    return float(len(_csv_таблица()))


