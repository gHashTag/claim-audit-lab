# -*- coding: utf-8 -*-
"""Машинный вопрос о согласованности высотной сводки zeta.

Кейс заново читает CSV десяти высотных корзин и текстовую сводку. Он не
принимает напечатанные среднее и разброс за вычислимый эталон и не объявляет
закон GUE подтверждённым. На настоящем входе первая строка CSV делает среднее
и разброс несовместимыми со сводкой: после исключения этой строки числа уже
приближаются к заявленным. Это устанавливает внутреннее несоответствие
артефактов, а вопрос о высотном тренде остаётся not-evaluated.
"""

from __future__ import annotations

import csv
import re
import statistics
from pathlib import Path

from goldsieve.sieve import Claim

КОРЕНЬ = Path(__file__).resolve().parent.parent
CSV = КОРЕНЬ.parent / "corpus" / "trinity" / "data" / "zeta" / "zeta_figure1_p95.csv"
СВОДКА = КОРЕНЬ.parent / "corpus" / "trinity" / "data" / "zeta" / "zeta_bin_analysis_update.md"
КОД_ВОПРОСА = "height_bin_summary_mismatch"


def _прочитать_csv() -> list[dict[str, float]]:
    with CSV.open(encoding="utf-8", newline="") as файл:
        строки = list(csv.DictReader(файл))
    if len(строки) != 10:
        raise AssertionError("CSV не предъявляет ровно десять высотных корзин")
    результат = []
    for строка in строки:
        результат.append({
            "T_mid": float(строка["T_mid"]),
            "p95": float(строка["p95"]),
            "GUE_p95": float(строка["GUE_p95"]),
        })
    return результат


def _прочитать_сводку() -> dict[str, float]:
    текст = СВОДКА.read_text(encoding="utf-8")
    совпадение = re.search(
        r"(?m)^\| p95 spacing \|\s*([0-9]+\.[0-9]+)\s*±\s*([0-9]+\.[0-9]+)\s*\|",
        текст,
    )
    if совпадение is None:
        raise AssertionError("сводка не предъявляет среднее и разброс p95")
    return {
        "среднее": float(совпадение.group(1)),
        "разброс": float(совпадение.group(2)),
    }


def _наблюдаемое() -> dict:
    строки = _прочитать_csv()
    сводка = _прочитать_сводку()
    значения = [строка["p95"] for строка in строки]
    среднее = statistics.mean(значения)
    разброс = statistics.pstdev(значения)
    допуск = 1e-4
    среднее_совпадает = abs(среднее - сводка["среднее"]) <= допуск
    разброс_совпадает = abs(разброс - сводка["разброс"]) <= допуск
    return {
        "число_корзин": len(строки),
        "среднее_csv": среднее,
        "разброс_csv": разброс,
        "среднее_сводки": сводка["среднее"],
        "разброс_сводки": сводка["разброс"],
        "первая_строка_p95": строки[0]["p95"],
        "минимум_csv": min(значения),
        "максимум_csv": max(значения),
        "среднее_совпадает": среднее_совпадает,
        "разброс_совпадает": разброс_совпадает,
        "есть_несоответствие": not (среднее_совпадает and разброс_совпадает),
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["есть_несоответствие"] = False
    результат["среднее_совпадает"] = True
    результат["разброс_совпадает"] = True
    return результат


def _контроль() -> float:
    наблюдение = _наблюдаемое()
    return float(sum([
        not наблюдение["среднее_совпадает"],
        not наблюдение["разброс_совпадает"],
    ]))


