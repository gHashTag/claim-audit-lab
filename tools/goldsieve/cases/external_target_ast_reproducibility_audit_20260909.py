# -*- coding: utf-8 -*-
"""Машинный вопрос о воспроизводимости шести нечитаемых AST-целей.

Этот маршрут заново разбирает исходники cases/*.py и фиксирует исходные
выражения полей value и uncertainty. Он не импортирует кейсы и не исполняет
выражения: до вычисления переменных и функций числовой внешний эталон не
предъявлен. Поэтому результатом является ВОПРОС, а не вердикт о внешней
величине.
"""

from __future__ import annotations

import ast
from pathlib import Path

from goldsieve.sieve import Claim


КЕЙСЫ = Path(__file__).resolve().parent.parent / "cases"
ИМЯ_САМОГО_КЕЙСА = Path(__file__).name
ПОЛЯ_ЦЕЛИ = ("value", "uncertainty")
КОД_ВОПРОСА = "external_target_ast_unreadable"


def _литеральный_ключ(узел: ast.AST):
    if isinstance(узел, ast.Constant):
        return узел.value
    return None


def _динамические_поля(узел: ast.Dict) -> list[str]:
    ключи = [_литеральный_ключ(ключ) for ключ in узел.keys]
    поля = {
        имя: значение
        for имя, значение in zip(ключи, узел.values)
        if имя in ПОЛЯ_ЦЕЛИ
    }
    динамические = []
    for имя in ПОЛЯ_ЦЕЛИ:
        if имя not in поля:
            continue
        try:
            ast.literal_eval(поля[имя])
        except (ValueError, SyntaxError):
            динамические.append(имя)
    return динамические


def _прочитать() -> list[dict]:
    записи = []
    for путь in sorted(КЕЙСЫ.glob("*.py")):
        if путь.name == ИМЯ_САМОГО_КЕЙСА:
            continue
        дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
        for узел in ast.walk(дерево):
            if not isinstance(узел, ast.Dict):
                continue
            динамические = _динамические_поля(узел)
            if not динамические:
                continue
            ключи = [_литеральный_ключ(ключ) for ключ in узел.keys]
            if not set(ПОЛЯ_ЦЕЛИ).issubset(ключи):
                continue
            записи.append({
                "файл": путь.name,
                "строка": узел.lineno,
                "поля": динамические,
            })
    return записи


def _наблюдаемое() -> dict:
    записи = _прочитать()
    по_полям = {
        имя: sum(имя in запись["поля"] for запись in записи)
        for имя in ПОЛЯ_ЦЕЛИ
    }
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
        "число_нечитаемых_целей": len(записи),
        "по_полям": по_полям,
        "цели": записи,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["число_нечитаемых_целей"] += 1
    return результат


def _контроль() -> float:
    return float(len(_прочитать()))


