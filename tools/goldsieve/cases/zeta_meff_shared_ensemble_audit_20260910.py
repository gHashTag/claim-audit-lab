КОРЕНЬ = Path(__file__).resolve().parent.parent
ОЖИДАЕМЫЕ_АРХИВЫ = 12
# Кейс использует штатный машинный код сита: отсутствие общего ансамбля
# делает эффективное число попыток неидентифицируемым.
КОД_ВОПРОСА = "meff_unstable"


def _записи(путь: Path) -> list[dict]:
    """Извлечь только записи С20 с числовыми M и M_eff."""
    документ = json.loads(путь.read_text(encoding="utf-8"))
    записи = []
    if not isinstance(документ, list):
        return записи
    for элемент in документ:
        if not isinstance(элемент, dict):
            continue
        результаты = элемент.get("results", [])
        if not isinstance(результаты, list):
            continue
        for результат in результаты:
            if not isinstance(результат, dict):
                continue
            if результат.get("sieve") != "С20 эффективное число попыток":
                continue
            числа = результат.get("numbers")
            if not isinstance(числа, dict):
                continue
            значение_m = числа.get("M")
            значение_meff = числа.get("M_eff")
            if (
                isinstance(значение_m, (int, float))
                and not isinstance(значение_m, bool)
                and isinstance(значение_meff, (int, float))
                and not isinstance(значение_meff, bool)
            ):
                записи.append(
                    {
                        "M": float(значение_m),
                        "M_eff": float(значение_meff),
                        "общий_M_eff": числа.get("M_eff_общий"),
                        "идентификатор": числа.get(
                            "идентификатор_общего_ансамбля"
                        ),
                    }
                )
    return записи


def _архивы() -> list[tuple[Path, list[dict]]]:
    найденные = []
    for путь in sorted(КОРЕНЬ.glob("*_external_*.json")):
        try:
            записи = _записи(путь)
        except (OSError, UnicodeError, json.JSONDecodeError):
            continue
        if len(записи) > 1:
            найденные.append((путь, записи))
    return найденные


АРХИВЫ = _архивы()
assert len(АРХИВЫ) == ОЖИДАЕМЫЕ_АРХИВЫ


def _есть_общий_ансамбль(запись: dict) -> bool:
    return (
        isinstance(запись["общий_M_eff"], (int, float))
        and not isinstance(запись["общий_M_eff"], bool)
        and isinstance(запись["идентификатор"], str)
        and bool(запись["идентификатор"].strip())
    )


def _наблюдаемое() -> dict:
    все = []
    по_архивам = {}
    for путь, записи in АРХИВЫ:
        все.extend(записи)
        по_архивам[путь.name] = {
            "записей_С20": len(записи),
            "с_общим_ансамблем": sum(
                1 for запись in записи if _есть_общий_ансамбль(запись)
            ),
            "M": sorted({запись["M"] for запись in записи}),
            "различных_M_eff": len({запись["M_eff"] for запись in записи}),
        }
    значения_m = sorted({запись["M"] for запись in все})
    общие = sum(1 for запись in все if _есть_общий_ансамбль(запись))
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
        "архивов_с_несколькими_С20": len(АРХИВЫ),
        "записей_С20": len(все),
        "различных_M": значения_m,
        "записей_с_общим_M_eff_и_идентификатором": общие,
        "архивы": по_архивам,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["записей_с_общим_M_eff_и_идентификатором"] = 1
    return результат


def _контроль() -> float:
    return float(_наблюдаемое()["архивов_с_несколькими_С20"])


Наблюдение = _наблюдаемое()
