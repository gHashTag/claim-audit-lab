"""Машинный вопрос о предъявлении общего ансамбля для M_eff.

Этот маршрут заново читает исходные JSON-архивы с несколькими записями сита
С20. Он не использует сводку сторожа: для каждой записи проверяется наличие
общего M_eff и непустого идентификатора ансамбля. Одинаковое M в архивах и
наличие отдельных M_eff не разрешают объединять испытания, пока общий
ансамбль не предъявлен.
"""

from __future__ import annotations

import json
import sys
