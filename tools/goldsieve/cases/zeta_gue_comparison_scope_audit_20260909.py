"""Машинный вопрос о сопоставимости наблюдаемого zeta и точного GUE.

Кейс читает один документ корпуса другим маршрутом: отдельно извлекает
наблюдаемое стандартное отклонение, точный эталон и описание развёртки.
Наличие этих трёх строк ещё не предъявляет общего паспорта выборки,
нормализации и границ сравнения. Поэтому отсутствие такого паспорта не
превращается в подтверждение закона zeta/GUE.
"""

from __future__ import annotations

import re
from pathlib import Path

from goldsieve.sieve import Claim

КОРПУС = Path(
    "/home/user/workspace/corpus/trinity/data/zeta/zeta_gue_analysis_results.md"
)
КОД_ВОПРОСА = "comparison_scope_undeclared"


def _прочитать() -> str:
    return КОРПУС.read_text(encoding="utf-8")


def _наблюдаемое() -> dict:
    текст = _прочитать()
    наблюдаемое = re.search(
        r"(?m)^\| Std deviation \|\s*([0-9]+\.[0-9]+)\s*\|", текст
    )
    точное = re.search(
        r"(?i)exact(?: Fredholm)? GUE gives\s*([0-9]+\.[0-9]+)", текст
    )
    если_нет_точного = re.search(
        r"(?m)^std\s+([0-9]+\.[0-9]+),\s+p50", текст
    )
    if наблюдаемое is None or (точное is None and если_нет_точного is None):
        raise AssertionError("корпус не предъявляет обе части сравнения")
    точное_значение = (
        float(точное.group(1)) if точное is not None else float(если_нет_точного.group(1))
    )
    есть_развёртка = bool(
        re.search(r"(?i)(unfolding|развёртк)[^\n]{0,180}", текст)
    )
    есть_общий_паспорт = bool(
        re.search(
            r"(?i)(same|один и тот же|общ(?:ая|ий))[^\n]{0,120}"
            r"(sample|выборк|normaliz|нормализац|границ|range|T\s*=)",
            текст,
        )
    )
    return {
        "наблюдаемое_std": float(наблюдаемое.group(1)),
        "точный_gue_std": точное_значение,
        "развёртка_упомянута": есть_развёртка,
        "общий_паспорт_сравнения": есть_общий_паспорт,
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _неверный_ответ() -> dict:
    результат = _наблюдаемое()
    результат["наблюдаемое_std"] += 1.0
    return результат


