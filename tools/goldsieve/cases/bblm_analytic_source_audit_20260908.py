# -*- coding: utf-8 -*-
"""Машинный вопрос о первоисточнике коэффициентов BBLM.

Кейс читает протокол JSON и текст спецификации самостоятельно, не принимая
отчёт сторожа за наблюдение. Наличие ссылки на статью и печатных коэффициентов
не заменяет аналитические выражения с номерами уравнений. Поэтому при
отсутствующем выводе итогом является ВОПРОС с причиной
``analytic_source_absent``, а научный статус остаётся ``not-evaluated``.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from goldsieve.sieve import Claim


if __name__ in __import__("sys").modules:
    raise RuntimeError("кейс должен загружаться через module_from_spec без регистрации")


КОРЕНЬ = Path(__file__).resolve().parent.parent
ПРОТОКОЛ = КОРЕНЬ / "bblm_protocol.json"
СПЕЦИФИКАЦИЯ = КОРЕНЬ / "bblm_spec.yaml"
КОД_ВОПРОСА = "analytic_source_absent"


def _прочитать_протокол() -> dict:
    документ = json.loads(ПРОТОКОЛ.read_text(encoding="utf-8"))
    элементы = документ.get("elements")
    if not isinstance(элементы, list):
        raise AssertionError("протокол не предъявляет список элементов")
    совпадения = [
        элемент for элемент in элементы
        if isinstance(элемент, dict)
        and элемент.get("element") == "coefficient_rederivation"
    ]
    if len(совпадения) != 1:
        raise AssertionError("коэффициентный элемент предъявлен не ровно один раз")
    return совпадения[0]


def _прочитать_спецификацию() -> dict:
    """Разобрать только нужный блок YAML как текст, без стороннего парсера."""
    текст = СПЕЦИФИКАЦИЯ.read_text(encoding="utf-8")
    начало = re.search(r"(?m)^coefficient_rederivation:\s*$", текст)
    if начало is None:
        raise AssertionError("блок coefficient_rederivation не найден")
    хвост = текст[начало.end():]
    следующий = re.search(r"(?m)^[A-Za-z_][A-Za-z0-9_]*:\s*$", хвост)
    блок = хвост if следующий is None else хвост[:следующий.start()]
    присутствует = re.search(r"(?m)^\s+present:\s*false\s*$", блок)
    код = re.search(
        r"(?m)^\s+machine_reason_code:\s*analytic_source_absent\s*$", блок
    )
    формула_уравнения = re.search(
        r"(?mi)^\s+(?:equation|equation_number|номер_уравнения)\s*:", блок
    )
    return {
        "блок_найден": True,
        "present_false": присутствует is not None,
        "код_найден": код is not None,
        "формула_с_номером_уравнения": формула_уравнения is not None,
    }


def _наблюдаемое() -> dict:
    """Получить факт отсутствия аналитического первоисточника двумя входами."""
    элемент = _прочитать_протокол()
    спецификация = _прочитать_спецификацию()
    протокол_не_предъявляет = (
        элемент.get("present") is False
        and элемент.get("declared_present") is False
        and элемент.get("код_вопроса") == КОД_ВОПРОСА
    )
    источник_не_предъявлен = (
        спецификация["блок_найден"]
        and спецификация["present_false"]
        and спецификация["код_найден"]
        and not спецификация["формула_с_номером_уравнения"]
    )
    return {
        "статус_входа": "verified-in-scope",
        "протокол_не_предъявляет": протокол_не_предъявляет,
        "источник_не_предъявлен": источник_не_предъявлен,
        "код_вопроса": КОД_ВОПРОСА,
        "научный_статус": "not-evaluated",
    }


def _ложное_наблюдаемое() -> dict:
    """Контроль формы: намеренно предъявляет источник как найденный."""
    результат = _наблюдаемое()
    результат["источник_не_предъявлен"] = False
    результат["код_вопроса"] = ""
    return результат


def _контроль_формы() -> float:
    результат = _наблюдаемое()
    return float(sum([
        bool(результат["протокол_не_предъявляет"]),
        bool(результат["источник_не_предъявлен"]),
    ]))


