"""Машинный вопрос о согласованности статуса утверждения zeta/GUE.

Кейс самостоятельно читает разделы корпуса Trinity, в которых одновременно
написано «Confirmed to ~2%» и оставлено «status: OPEN». Такое соседство не
является новым численным эталоном: оно показывает, что формулировка
подтверждения не отделена от открытого статуса высотного анализа. При
отсутствии единого вычислимого паспорта входа научный статус остаётся
``not-evaluated``.
"""

from __future__ import annotations

import re
from pathlib import Path

from goldsieve.sieve import Claim


КОРПУС = Path(
    "/home/user/workspace/corpus/trinity/data/zeta/zeta_gue_analysis_results.md"
)
КОД_ВОПРОСА = "unqualified_gue_claim"


def _прочитать() -> str:
    return КОРПУС.read_text(encoding="utf-8")


def _наблюдаемое() -> dict:
    текст = _прочитать()
    строка_подтверждения = re.search(
        r"(?im)^###\s+1\.\s+Montgomery-Odlyzko Law:\s*"
        r"Confirmed to ~2%[^\n]*$",
        текст,
    )
    строка_открытого_статуса = re.search(
        r"(?im)^###\s+2\.\s+Height Paradox\s+—\s+status:\s*OPEN[^\n]*$",
        текст,
    )
    ограничение_точности = bool(
        re.search(
            r"(?im)Any claim finer than a few percent needs the exact law",
            текст,
        )
    )
    есть_воспроизводимый_паспорт = bool(
        re.search(
            r"(?is)(?:reproducible|воспроизводим)[^\n]{0,160}"
            r"(?:parameters|параметр|uncertainty|погрешност)",
            текст,
        )
    )
    return {
        "строка_подтверждения_найдена": строка_подтверждения is not None,
        "строка_открытого_статуса_найдена": строка_открытого_статуса is not None,
        "ограничение_точности_найдено": ограничение_точности,
        "единый_воспроизводимый_паспорт_найден": есть_воспроизводимый_паспорт,
        "заявление_и_открытый_статус_сосуществуют": (
            строка_подтверждения is not None
            and строка_открытого_статуса is not None
        ),
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["заявление_и_открытый_статус_сосуществуют"] = False
    return результат


def _контроль() -> float:
    результат = _наблюдаемое()
    return float(
        результат["строка_подтверждения_найдена"]
        and результат["строка_открытого_статуса_найдена"]
    )


Наблюдение = _наблюдаемое()
assert Наблюдение["строка_подтверждения_найдена"]
assert Наблюдение["строка_открытого_статуса_найдена"]
assert Наблюдение["ограничение_точности_найдено"]
assert Наблюдение["заявление_и_открытый_статус_сосуществуют"]
assert Наблюдение["научный_статус"] == "not-evaluated"
assert _контроль() == 1.0
assert not _ложное_наблюдаемое()["заявление_и_открытый_статус_сосуществуют"]


