# -*- coding: utf-8 -*-
"""Машинный вопрос о полном составе обязательных элементов BBLM.

Кейс самостоятельно сопоставляет протокол восьми элементов с двумя
учётными артефактами. Он не считает численные коэффициенты из спецификации
аналитическим выводом и не использует отчёт сторожа как наблюдение. Сейчас
семь элементов предъявлены, а коэффициентный первоисточник отсутствует;
поэтому итог остаётся ВОПРОСОМ с причиной analytic_source_absent и научным
статусом not-evaluated.
"""

from __future__ import annotations

import json
from pathlib import Path

from goldsieve.sieve import Claim


КОРЕНЬ = Path(__file__).resolve().parent.parent
ПРОТОКОЛ = КОРЕНЬ / "bblm_protocol.json"
ЭЛЕМЕНТЫ = КОРЕНЬ / "bblm_elements.json"
УЧЁТ = КОРЕНЬ / "bblm_accounting.json"
КОД_ВОПРОСА = "analytic_source_absent"
ОЖИДАЕМЫЙ_ИТОГ = {"всего": 8, "предъявлено": 7, "отсутствует": 1}


def _загрузить(путь: Path) -> dict:
    значение = json.loads(путь.read_text(encoding="utf-8"))
    if not isinstance(значение, dict):
        raise AssertionError("артефакт не является JSON-объектом: %s" % путь.name)
    return значение


def _сводка() -> dict:
    протокол = _загрузить(ПРОТОКОЛ)
    элементы = _загрузить(ЭЛЕМЕНТЫ)
    учёт = _загрузить(УЧЁТ)
    строки = протокол.get("elements")
    if not isinstance(строки, list) or len(строки) != ОЖИДАЕМЫЙ_ИТОГ["всего"]:
        raise AssertionError("протокол не предъявляет ровно восемь элементов")
    корректные = [
        строка for строка in строки
        if isinstance(строка, dict)
        and isinstance(строка.get("element"), str)
        and isinstance(строка.get("present"), bool)
        and isinstance(строка.get("declared_present"), bool)
    ]
    if len(корректные) != len(строки):
        raise AssertionError("в протоколе есть неполные строки элементов")
    по_протоколу_предъявлено = sum(
        строка["present"] and строка["declared_present"] for строка in корректные
    )
    отсутствующие = [
        строка["element"] for строка in корректные if not строка["present"]
    ]
    открытые = элементы.get("elements_open_with_machine_question")
    если_нет_открытых = not isinstance(открытые, list)
    открытые_имена = [
        строка.get("element") for строка in открытые or []
        if isinstance(строка, dict) and isinstance(строка.get("element"), str)
    ]
    учётные_предъявленные = учёт.get("spec_present")
    учётные_открытые = учёт.get("open_with_machine_question")
    if not isinstance(учётные_предъявленные, list):
        raise AssertionError("учёт не предъявляет список present")
    if not isinstance(учётные_открытые, list):
        raise AssertionError("учёт не предъявляет список открытых элементов")
    учётный_итог = {
        "всего": len(учётные_предъявленные) + len(учётные_открытые),
        "предъявлено": len(учётные_предъявленные),
        "отсутствует": len(учётные_открытые),
    }
    источник_отсутствует = (
        отсутствующие == ["coefficient_rederivation"]
        and any(
            isinstance(строка, dict)
            and строка.get("element") == "coefficient_rederivation"
            and строка.get("код_вопроса") == КОД_ВОПРОСА
            for строка in корректные
        )
    )
    согласованность = (
        len(корректные) == учётный_итог["всего"] == ОЖИДАЕМЫЙ_ИТОГ["всего"]
        and по_протоколу_предъявлено == учётный_итог["предъявлено"] == ОЖИДАЕМЫЙ_ИТОГ["предъявлено"]
        and len(отсутствующие) == учётный_итог["отсутствует"] == ОЖИДАЕМЫЙ_ИТОГ["отсутствует"]
        and not если_нет_открытых
        and sorted(открытые_имена) == sorted(отсутствующие)
        and sorted(учётные_открытые) == sorted(отсутствующие)
    )
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "обязательных_элементов": len(корректные),
        "предъявленных_элементов": по_протоколу_предъявлено,
        "отсутствующих_элементов": отсутствующие,
        "открытых_элементов_в_учёте": sorted(открытые_имена),
        "учётная_сводка": учётный_итог,
        "артефакты_согласованы": согласованность,
        "аналитический_источник_коэффициентов_отсутствует": источник_отсутствует,
        "ссылка_на_источник": "https://arxiv.org/abs/nlin/0601006",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _наблюдаемое() -> dict:
    return _сводка()


def _ложное_наблюдаемое() -> dict:
    результат = _сводка()
    результат["аналитический_источник_коэффициентов_отсутствует"] = False
    результат["отсутствующих_элементов"] = []
    return результат


def _контроль() -> float:
    результат = _сводка()
    return float(len(результат["отсутствующих_элементов"]))


