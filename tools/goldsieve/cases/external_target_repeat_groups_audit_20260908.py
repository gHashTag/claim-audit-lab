# -*- coding: utf-8 -*-
"""Машинный вопрос о слиянии повторов внешних целей.

Кейс самостоятельно разбирает AST файлов cases/*.py и собирает только
буквальные словари внешних целей. Он не читает отчёт сторожа новизны и не
считает повторные файлы независимыми измерениями. Семь групп повторов охватывают
15 кейсов; без решения, какие записи являются одним экспериментом, объединённый
вывод о внешней цели остаётся ВОПРОСОМ.
"""

from __future__ import annotations

import ast
import math
from pathlib import Path
from urllib.parse import urlparse

from goldsieve.sieve import Claim


КОРЕНЬ = Path(__file__).resolve().parent.parent
КЕЙСЫ = КОРЕНЬ / "cases"


def _литерал(узел: ast.AST):
    try:
        return ast.literal_eval(узел)
    except (ValueError, SyntaxError):
        return None


def _отпечаток(значение: float, неопределённость: float, источник: str) -> str:
    """Стабильная группировка по числу, неопределённости и узлу источника."""
    def округлить(число: float) -> str:
        if число == 0:
            return "0"
        порядок = math.floor(math.log10(abs(число)))
        мантисса = число / (10.0 ** порядок)
        шаг = 1e-6
        мантисса = round(мантисса / шаг) * шаг
        return f"{мантисса:.6f}e{порядок}"

    узел = urlparse(str(источник)).netloc.lower()
    if узел.startswith("www."):
        узел = узел[4:]
    return f"{округлить(значение)}|{округлить(неопределённость)}|{узел}"


def _цели(путь: Path) -> list[tuple[str, str]]:
    """Прочитать цели AST-разбором, не импортируя кейсы и не вызывая их."""
    дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
    найденные = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Dict):
            continue
        ключи = [ключ.value if isinstance(ключ, ast.Constant) else None
                 for ключ in узел.keys]
        if "value" not in ключи or "uncertainty" not in ключи:
            continue
        поля = {}
        for ключ, значение in zip(ключи, узел.values):
            if ключ is not None:
                поля[ключ] = _литерал(значение)
        try:
            число = float(поля["value"])
            ошибка = float(поля["uncertainty"])
            источник = str(поля.get("source") or поля.get("url") or "")
        except (KeyError, TypeError, ValueError):
            continue
        if not math.isfinite(число) or not math.isfinite(ошибка):
            continue
        найденные.append((_отпечаток(число, ошибка, источник), путь.name))
    return найденные


def _наблюдаемое() -> dict:
    """Независимо пересчитать группы и число кейсов в повторяющихся группах."""
    группы: dict[str, set[str]] = {}
    прочитано = 0
    ошибки = 0
    for путь in sorted(КЕЙСЫ.glob("*.py")):
        try:
            цели = _цели(путь)
        except (OSError, UnicodeError, SyntaxError):
            ошибки += 1
            continue
        прочитано += 1
        for отпечаток, имя in цели:
            группы.setdefault(отпечаток, set()).add(имя)
    повторы = {ключ: sorted(имена) for ключ, имена in группы.items()
               if len(имена) > 1}
    return {
        "прочитано_кейсов": прочитано,
        "ошибок_разбора": ошибки,
        "групп_целей": len(группы),
        "групп_повторов": len(повторы),
        "кейсов_в_повторах": sum(len(имена) for имена in повторы.values()),
        "повторы": повторы,
    }


def _ложное_наблюдаемое() -> dict:
    """Контроль формы: намеренно меняет число групп, но не входные файлы."""
    результат = _наблюдаемое()
    результат["групп_повторов"] += 1
    return результат


