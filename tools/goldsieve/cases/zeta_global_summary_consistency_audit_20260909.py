# -*- coding: utf-8 -*-
"""Машинный вопрос о внутренней согласованности глобальной сводки zeta.

Кейс заново читает один текстовый файл корпуса и сопоставляет строку глобальной
таблицы со старым числом, которое тот же файл называет противоречащим таблице.
Это не внешний эталон и не доказательство закона GUE: найденное расхождение
делает вопрос о том, какая редакция сводки является входом, not-evaluated.
"""

from __future__ import annotations

import re
from pathlib import Path

from goldsieve.sieve import Claim

КОРПУС = (
    Path(__file__).resolve().parent.parent.parent
    / "corpus" / "trinity" / "data" / "zeta" / "zeta_gue_analysis_results.md"
)
КОД_ВОПРОСА = "global_summary_inconsistent"


def _прочитать() -> dict[str, float | bool | str]:
    текст = КОРПУС.read_text(encoding="utf-8")
    строка = re.search(
        r"(?m)^\| Std deviation \|\s*([0-9]+\.[0-9]+)\s*\|\s*"
        r"([0-9]+\.[0-9]+)\s*\|\s*([-+−]?[0-9]+\.[0-9]+)%\s*\|",
        текст,
    )
    if строка is None:
        raise AssertionError("строка Std deviation в глобальной таблице не найдена")
    старое = re.search(
        r"global std of\s+([0-9]+\.[0-9]+)\s+contradicted",
        текст,
    )
    if старое is None:
        raise AssertionError("текст не предъявляет прежнее противоречащее std")
    табличное = float(строка.group(1))
    прежнее = float(старое.group(1))
    return {
        "табличное_std": табличное,
        "табличный_эталон_std": float(строка.group(2)),
        "табличное_отклонение_процентов": float(строка.group(3).replace("−", "-")),
        "прежнее_std_в_тексте": прежнее,
        "разность": abs(табличное - прежнее),
        "согласуется": табличное == прежнее,
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _наблюдаемое() -> dict[str, float | bool | str]:
    return _прочитать()


def _ложное_наблюдаемое() -> dict[str, float | bool | str]:
    результат = _прочитать()
    результат["согласуется"] = True
    результат["разность"] = 0.0
    return результат


def _контроль() -> float:
    наблюдение = _прочитать()
    return float(наблюдение["разность"] > 0.0)


