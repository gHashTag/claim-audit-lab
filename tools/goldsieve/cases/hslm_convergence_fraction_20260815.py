"""Проверка доли выполненного расписания обучения HSLM.

Наблюдение извлекает напечатанные шаги сходимости и процент из отчёта.
Основной эталон независимо считает отношение шагов к полному расписанию.
Альтернативный эталон выполняет то же отношение в Decimal, не используя
напечатанный процент. Подставка и отрицательный контроль обязаны различаться.
"""

import re
from decimal import Decimal, localcontext

from goldsieve.sieve import Claim

ИСТОЧНИК = (
    "/home/user/workspace/corpus/trinity/docs/research/bundles/B001_HSLM.md"
)
ШАГ_СХОЖДЕНИЯ = 47832
ПОЛНЫЙ_ГРАФИК = 50000


def _текст():
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def _наблюдение():
    совпадение = re.search(
        r"Training converged at step\s+([0-9,]+)\s+\(([-0-9.]+)% of scheduled\)",
        _текст(),
    )
    if not совпадение:
        raise AssertionError("строка сходимости не найдена")
    шаги = int(совпадение.group(1).replace(",", ""))
    процент = float(совпадение.group(2))
    if шаги != ШАГ_СХОЖДЕНИЯ:
        raise AssertionError("напечатанный шаг изменился")
    return процент


def _эталон():
    """Вычислимый эталон: доля шагов полного расписания."""
    return 100.0 * ШАГ_СХОЖДЕНИЯ / ПОЛНЫЙ_ГРАФИК


def _эталон_альт():
    """Независимый путь: десятичное деление с повышенной точностью."""
    with localcontext() as контекст:
        контекст.prec = 40
        return float(Decimal(100) * Decimal(ШАГ_СХОЖДЕНИЯ) / Decimal(ПОЛНЫЙ_ГРАФИК))


def _подставка():
    return 90.0


def _отрицательный_контроль():
    """Полное расписание — другой режим, а не повторение эталона."""
    return 100.0


def _самопроверка():
    assert _наблюдение() == 95.7
    assert abs(_эталон() - 95.664) < 1.0e-12
    assert abs(_эталон_альт() - _эталон()) < 1.0e-12
    assert _подставка() != _эталон()
    assert _отрицательный_контроль() != _эталон()


_самопроверка()


