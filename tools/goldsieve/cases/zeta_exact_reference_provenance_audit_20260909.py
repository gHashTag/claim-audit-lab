"""Машинный вопрос о воспроизводимости точного эталона GUE.

Кейс читает запись корпуса и исходник вычислимого закона, не выполняя
numpy-расчёт и не принимая напечатанное десятичное число за эталон. Наличие
функции GapLaw и формулы детерминанта показывает только предъявленный маршрут;
сохранённого результата запуска с параметрами и погрешностью нет. Поэтому
итогом остаётся ВОПРОС, а научный статус не меняется на подтверждённый.
"""

from __future__ import annotations

import re
from pathlib import Path

from goldsieve.sieve import Claim

КОРЕНЬ = Path(__file__).resolve().parent.parent
КОРПУС = Path("/home/user/workspace/corpus/trinity/data/zeta/zeta_gue_analysis_results.md")
ИСТОЧНИК = Path("/home/user/workspace/corpus/trinity/scripts/gue_exact_gap.py")
КОД_ВОПРОСА = "no_computable_reference"


def _прочитать() -> dict:
    текст = КОРПУС.read_text(encoding="utf-8")
    исходник = ИСТОЧНИК.read_text(encoding="utf-8")
    совпадение = re.search(
        r"exact Fredholm GUE gives\s+([0-9]+\.[0-9]+)", текст
    )
    if совпадение is None:
        raise AssertionError("корпус не предъявляет десятичную запись точного GUE")
    значение = float(совпадение.group(1))
    маршрут = all(
        фрагмент in исходник
        for фрагмент in ("class GapLaw", "def std", "def e2_no_eigenvalue")
    )
    есть_артефакт_запуска = bool(re.search(
        r"(?im)^(?:run|результат|output|вывод)\s*[:=]", текст
    ))
    return {
        "значение_в_корпусе": значение,
        "маршрут_предъявлен": маршрут,
        "артефакт_запуска_с_параметрами": есть_артефакт_запуска,
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _наблюдаемое() -> dict:
    return _прочитать()


def _неверный_ответ() -> dict:
    результат = _прочитать()
    результат["маршрут_предъявлен"] = False
    return результат


