"""Аудит точного p-значения из примера Wilcoxon V20.

Наблюдение извлекается из напечатанной строки отчёта. Эталон отдельно строит
разности пар, ранги со средними рангами при совпадении и точное распределение
знаков. Второй эталон считает ту же вероятность другим перечислением
подмножеств; он не читает напечатанное p-значение.
"""

