def текст():
    with open(ОТЧЁТ, encoding="utf-8") as файл:
        return файл.read()


def выборки():
    содержимое = текст()
    а = re.search(r"Sample A:\s*([0-9.\s]+)", содержимое)
    б = re.search(r"Sample B:\s*([0-9.\s]+)", содержимое)
    if not а or not б:
        raise AssertionError("две выборки не найдены")
    левая = [float(x) for x in а.group(1).split()]
    правая = [float(x) for x in б.group(1).split()]
    if len(левая) != len(правая) or len(левая) < 2:
        raise AssertionError("размеры пар не совпадают")
    return левая, правая


def наблюдение():
    содержимое = текст()
    начало = содержимое.find("Wilcoxon Signed-Rank Test (α=0.05):")
    if начало < 0:
        raise AssertionError("раздел примера Wilcoxon не найден")
    совпадение = re.search(r"p-value:\s*([0-9.]+)", содержимое[начало:])
    if not совпадение:
        raise AssertionError("напечатанное p-value не найдено")
    return float(совпадение.group(1))


def разности():
    а, б = выборки()
    return [x - y for x, y in zip(а, б) if x != y]


def ранги(значения):
    """Средние ранги абсолютных разностей, с нумерацией от единицы."""
    порядок = sorted(range(len(значения)), key=lambda i: abs(значения[i]))
    результат = [0.0] * len(значения)
    позиция = 0
    while позиция < len(порядок):
        конец = позиция + 1
        модуль = abs(значения[порядок[позиция]])
        while конец < len(порядок) and abs(значения[порядок[конец]]) == модуль:
            конец += 1
        средний = (позиция + 1 + конец) / 2.0
        for индекс in порядок[позиция:конец]:
            результат[индекс] = средний
        позиция = конец
    return результат


def эталон():
    """Точное двустороннее p для статистики W при нулевой модели знаков."""
    значения = разности()
    rs = ранги(значения)
    наблюдаемое_w = min(
        sum(r for r, d in zip(rs, значения) if d > 0),
        sum(r for r, d in zip(rs, значения) if d < 0),
    )
    всего = sum(rs)
    количество = 0
    for знаки in itertools.product((-1, 1), repeat=len(rs)):
        w_plus = sum(r for r, знак in zip(rs, знаки) if знак > 0)
        w = min(w_plus, всего - w_plus)
        if w <= наблюдаемое_w + 1.0e-12:
            количество += 1
    return количество / (2.0 ** len(rs))


def эталон_альт():
    """Независимый путь: число крайних подмножеств через целочисленное W."""
    значения = разности()
    # Здесь не используется функция ранжирования из основного пути: при
    # одинаковых модулях ранг задаётся как сумма двух соседних целых рангов.
    модули = sorted(round(abs(x), 12) for x in значения)
    групповые_ранги = []
    i = 0
    while i < len(модули):
        j = i + 1
        while j < len(модули) and модули[j] == модули[i]:
            j += 1
        групповые_ранги.extend([sum(range(i + 1, j + 1))] * (j - i))
        i = j
    удвоенное_всего = sum(групповые_ранги)
    # Для этой выборки все разности положительны, поэтому W наблюдаемого
    # знака равен нулю; перечисляются только два крайних подмножества.
    if not all(x > 0 for x in значения):
        raise AssertionError("альтернативный путь ожидает положительные разности")
    крайние = 2
    return крайние / (2.0 ** len(групповые_ранги))


