"""Аудит рецепта заявления 190/190 в отчёте Level 11.30.

Цель кейса — не подтвердить отношение двух напечатанных чисел. Проверяется,
раскрыт ли экспериментальный рецепт, достаточный для воспроизведения доли
правильных ответов: сами запросы и ответы, правило оценки, разбиение, seed,
версия реализации и независимая проверка. При отсутствии этого инвентаря сито
не подменяется догадкой и возвращает ВОПРОС.
"""

import os
import re
import sys

from goldsieve.sieve import Claim

ИСТОЧНИК = "/home/user/workspace/corpus/trinity/deploy/trinity-nexus/docs/research/trinity-level11-planning-sota-report.md"

# Защита от тихого обхода реального режима CLI.
if __name__ in sys.modules:
    raise RuntimeError("кейс должен загружаться без регистрации в sys.modules")


def _текст():
    if not os.path.isfile(ИСТОЧНИК):
        raise AssertionError("отчёт Level 11.30 отсутствует")
    with open(ИСТОЧНИК, encoding="utf-8") as файл:
        return файл.read()


def наблюдение():
    текст = _текст()
    совпадение = re.search(r"(\d+) queries,\s*(\d+) correct\s*\(100%\)", текст)
    if not совпадение:
        raise AssertionError("сводка 190/190 не найдена")
    всего, правильных = map(int, совпадение.groups())
    if всего != 190 or правильных != 190:
        raise AssertionError("сводка изменилась")
    return правильных / всего


def _инвентарь_рецепта():
    текст = _текст().lower()
    # Проверяем только текст отчёта, а не достраиваем отсутствующие сведения.
    поля = {
        "сырые запросы": bool(re.search(r"raw queries|query list|test cases|набор запрос", текст)),
        "эталонные ответы": bool(re.search(r"ground truth|expected answers|gold answers|эталонн", текст)),
        "правило оценки": bool(re.search(r"evaluation rule|scoring rule|метрик[аи] оцен", текст)),
        "разбиение": bool(re.search(r"train.?test split|held.?out|разбиен|отложенн", текст)),
        "seed": bool(re.search(r"\bseed\b|random seed|начальн(?:ое|ый) состояние", текст)),
        "версия реализации": bool(re.search(r"commit|git sha|version|верси[яи] реализации", текст)),
        "независимая проверка": bool(re.search(r"independent|external validation|independent replay|независим", текст)),
    }
    поля["рецепт_полон"] = all(поля.values())
    поля["отсутствует"] = [имя for имя, есть in поля.items()
                           if имя not in {"рецепт_полон", "отсутствует"} and not есть]
    return поля


def _код_причины():
    return "" if _инвентарь_рецепта()["рецепт_полон"] else "metrics_incommensurable"


def _неверный_ответ():
    return 0.5


def _контроль():
    # Контроль намеренно не равен заявлению: это отрицательная подставка для
    # проверки, что отсутствие рецепта не маскируется совпадением долей.
    return 0.0


def _самопроверка():
    assert наблюдение() == 1.0
    инвентарь = _инвентарь_рецепта()
    assert not инвентарь["рецепт_полон"]
    assert set(инвентарь["отсутствует"]) == {
        "сырые запросы", "эталонные ответы", "правило оценки", "разбиение",
        "seed", "версия реализации", "независимая проверка",
    }
    assert _код_причины() == "metrics_incommensurable"
    assert _неверный_ответ() != наблюдение()
    assert _контроль() != наблюдение()


_самопроверка()

