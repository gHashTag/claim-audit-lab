"""Аудит отдельного сравнения кандидатов параметра гамма в DELTA-001.

Наблюдение извлекается из строки отчёта. Эталон заново вычисляет относительное
расхождение между φ⁻³ и кандидатом 0,274. Альтернативный эталон использует
Decimal.sqrt и Decimal-степень, поэтому не читает и не повторяет вычисление
наблюдения.
"""

import re
from decimal import Decimal, getcontext

from goldsieve.sieve import Claim

ИСТОЧНИК = "/home/user/workspace/corpus/trinity/docs/docs/research/delta-001/phase4-consistency.md"


def _текст():
    return open(ИСТОЧНИК, encoding="utf-8").read()


def _наблюдение():
    шаблон = r"\| \*\*Black hole entropy\*\* \| ([0-9.]+)% error \|"
    совпадение = re.search(шаблон, _текст())
    if not совпадение:
        raise AssertionError("строка сравнения с Meissner не найдена")
    return float(совпадение.group(1))


def _эталон():
    phi = (1.0 + 5.0 ** 0.5) / 2.0
    гамма = phi ** -3
    кандидат = 0.274
    return abs(гамма - кандидат) / abs(кандидат) * 100.0


def _эталон_альт():
    getcontext().prec = 70
    phi = (Decimal(1) + Decimal(5).sqrt()) / Decimal(2)
    гамма = Decimal(1) / (phi ** Decimal(3))
    кандидат = Decimal("0.274")
    return float(abs(гамма - кандидат) / abs(кандидат) * Decimal(100))


def _неверный_ответ_ноль():
    return 0.0


def _неверный_ответ_другой_кандидат():
    phi = (1.0 + 5.0 ** 0.5) / 2.0
    гамма = phi ** -3
    кандидат = 0.23753295805014464
    return abs(гамма - кандидат) / abs(кандидат) * 100.0


def _положительный_контроль():
    return _эталон_альт()


def _выборка():
    return [_наблюдение()]


def _среднее(значения):
    return float(sum(значения) / len(значения))


def _самопроверка():
    assert abs(_эталон() - 13.84380383219356) < 1.0e-12
    assert abs(_эталон_альт() - _эталон()) < 1.0e-12
    assert abs(_наблюдение() - 13.9) < 1.0e-12
    assert _неверный_ответ_ноль() != _эталон()
    assert abs(_неверный_ответ_другой_кандидат() - _эталон()) > 1.0


_самопроверка()

