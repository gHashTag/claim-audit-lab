# -*- coding: utf-8 -*-
"""Машинный вопрос о применимости поправки Шидака к перебору формул.

Кейс получает вход другим маршрутом: он разбирает AST конкретного кейса
порога Шидака, не импортирует его и не читает отчёт сторожа независимости.
Так проверяется, что число перебранных формул и декларация предпосылки
действительно предъявлены в исходнике. Декларация ``unknown`` не превращается
в доказанную независимость, поэтому научный итог остаётся ``not-evaluated``.
"""

from __future__ import annotations

import ast
from pathlib import Path

from goldsieve.sieve import Claim


КОРЕНЬ = Path(__file__).resolve().parent.parent
ИСТОЧНИК = КОРЕНЬ / "cases" / "sidak_threshold_20260815.py"
КОД_ВОПРОСА = "sidak_independence_unverified"


def _литерал(узел: ast.AST):
    if isinstance(узел, ast.Constant):
        return узел.value
    return None


def _это_claim(узел: ast.Call) -> bool:
    функция = узел.func
    return (
        isinstance(функция, ast.Name)
        and функция.id == "Claim"
    ) or (
        isinstance(функция, ast.Attribute)
        and функция.attr == "Claim"
    )


def _наблюдаемое() -> dict:
    """Извлечь число испытаний и статус предпосылки из AST исходного кейса."""
    текст = ИСТОЧНИК.read_text(encoding="utf-8")
    дерево = ast.parse(текст, filename=str(ИСТОЧНИК))
    число_попыток = None
    семейная_ошибка = None
    подходящие = []
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Assign) and len(узел.targets) == 1:
            имя = узел.targets[0]
            if isinstance(имя, ast.Name) and имя.id == "ЧИСЛО_ПОПЫТОК":
                число_попыток = _литерал(узел.value)
            if isinstance(имя, ast.Name) and имя.id == "СЕМЕЙНАЯ_ОШИБКА":
                семейная_ошибка = _литерал(узел.value)
        if not isinstance(узел, ast.Call) or not _это_claim(узел):
            continue
        поля = {ключ.arg: ключ.value for ключ in узел.keywords if ключ.arg}
        имя = _литерал(поля.get("name"))
        if isinstance(имя, str) and "Шидак" in имя:
            подходящие.append({
                "имя": имя,
                "tests_independent": _литерал(
                    поля.get("tests_independent")
                ),
                "поле_предпосылки_есть": "tests_independent" in поля,
            })
    if число_попыток is None or семейная_ошибка is None:
        raise AssertionError("параметры порога не предъявлены литералами AST")
    if len(подходящие) != 1:
        raise AssertionError("не найден ровно один Claim порога Шидака")
    декларация = подходящие[0]["tests_independent"]
    неизвестна = декларация in (None, "unknown", "not-declared")
    return {
        "источник": str(ИСТОЧНИК),
        "число_перебранных_формул": число_попыток,
        "семейная_ошибка": семейная_ошибка,
        "число_целевых_claim": len(подходящие),
        "декларация_независимости": декларация,
        "поле_предпосылки_есть": подходящие[0]["поле_предпосылки_есть"],
        "предпосылка_не_установлена": неизвестна,
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["предпосылка_не_установлена"] = False
    результат["декларация_независимости"] = True
    return результат


def _контроль() -> float:
    return float(_наблюдаемое()["предпосылка_не_установлена"])


