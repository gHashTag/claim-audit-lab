"""Машинный вопрос о происхождении повторных внешних целей.

Кейс отдельно от группировщика проверяет, предъявлены ли у повторяющихся
целей идентификаторы эксперимента, набора данных или запуска. Совпадение
числа, неопределённости и узла источника не является таким идентификатором.
Без происхождения объединение 15 записей из 7 групп остаётся научно
неоценённым и даёт машинный ВОПРОС.
"""

from __future__ import annotations

import ast
import math
from pathlib import Path
from urllib.parse import urlparse

from goldsieve.sieve import Claim


if __name__ in __import__("sys").modules:
    raise RuntimeError("кейс должен загружаться через module_from_spec без регистрации")

КОРЕНЬ = Path(__file__).resolve().parent.parent
КЕЙСЫ = КОРЕНЬ / "cases"
КОД_ВОПРОСА = "repeat_provenance_undeclared"
ПОЛЯ_ПРОИСХОЖДЕНИЯ = {
    "experiment_id", "experiment", "experiment_identifier", "measurement_id",
    "run_id", "dataset_id", "source_id", "citation_key",
}


def _литерал(узел: ast.AST):
    try:
        return ast.literal_eval(узел)
    except (ValueError, SyntaxError):
        return None


def _округлить(число: float) -> str:
    if число == 0:
        return "0"
    порядок = math.floor(math.log10(abs(число)))
    мантисса = число / (10.0 ** порядок)
    мантисса = round(мантисса / 1e-6) * 1e-6
    return f"{мантисса:.6f}e{порядок}"


def _отпечаток(значение: float, ошибка: float, источник: str) -> str:
    узел = urlparse(str(источник)).netloc.lower()
    if узел.startswith("www."):
        узел = узел[4:]
    return f"{_округлить(значение)}|{_округлить(ошибка)}|{узел}"


def _цели(путь: Path) -> list[dict]:
    дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
    найденные = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Dict):
            continue
        ключи = [ключ.value if isinstance(ключ, ast.Constant) else None
                 for ключ in узел.keys]
        if "value" not in ключи or "uncertainty" not in ключи:
            continue
        поля = {
            ключ: _литерал(значение)
            for ключ, значение in zip(ключи, узел.values)
            if ключ is not None
        }
        try:
            значение = float(поля["value"])
            ошибка = float(поля["uncertainty"])
        except (KeyError, TypeError, ValueError):
            continue
        if not math.isfinite(значение) or not math.isfinite(ошибка):
            continue
        источник = str(поля.get("source") or поля.get("url") or "")
        идентификаторы = sorted(
            имя for имя in ПОЛЯ_ПРОИСХОЖДЕНИЯ
            if isinstance(поля.get(имя), (str, int, float))
            and str(поля.get(имя)).strip()
        )
        найденные.append({
            "отпечаток": _отпечаток(значение, ошибка, источник),
            "файл": путь.name,
            "строка": узел.lineno,
            "идентификаторы_происхождения": идентификаторы,
        })
    return найденные


def _наблюдаемое() -> dict:
    группы: dict[str, list[dict]] = {}
    прочитано = 0
    ошибки = 0
    for путь in sorted(КЕЙСЫ.glob("*.py")):
        try:
            цели = _цели(путь)
        except (OSError, UnicodeError, SyntaxError):
            ошибки += 1
            continue
        прочитано += 1
        for цель in цели:
            группы.setdefault(цель["отпечаток"], []).append(цель)
    повторы = {
        отпечаток: записи for отпечаток, записи in группы.items()
        if len({запись["файл"] for запись in записи}) > 1
    }
    без_идентификатора = [
        запись for записи in повторы.values() for запись in записи
        if not запись["идентификаторы_происхождения"]
    ]
    return {
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
        "прочитано_кейсов": прочитано,
        "ошибок_разбора": ошибки,
        "групп_повторов": len(повторы),
        "кейсов_в_повторах": sum(len(записи) for записи in повторы.values()),
        "записей_без_идентификатора": len(без_идентификатора),
        "повторы": повторы,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["записей_без_идентификатора"] += 1
    return результат


def _контроль() -> float:
    return float(_наблюдаемое()["записей_без_идентификатора"])


