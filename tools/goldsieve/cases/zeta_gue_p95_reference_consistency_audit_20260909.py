КОРЕНЬ = Path(__file__).resolve().parent.parent
СВОДКА = (
    КОРЕНЬ.parent
    / "corpus"
    / "trinity"
    / "data"
    / "zeta"
    / "zeta_bin_analysis_update.md"
)
CSV = (
    КОРЕНЬ.parent
    / "corpus"
    / "trinity"
    / "data"
    / "zeta"
    / "zeta_figure1_p95.csv"
)
КОД_ВОПРОСА = "gue_p95_reference_inconsistent"


def _прочитать_сводку() -> tuple[float, float]:
    текст = СВОДКА.read_text(encoding="utf-8")
    совпадение = re.search(
        r"std\s+0\.424258,\s+p50\s+[0-9.]+,\s+p90\s+[0-9.]+,\s+"
        r"p95\s+([0-9]+\.[0-9]+),\s+p99\s+[0-9.]+",
        текст,
    )
    if совпадение is None:
        raise AssertionError("точная строка p95 поздней поправки не найдена")
    точный_p95 = float(совпадение.group(1))
    строка = re.search(
        r"^\|\s*p95 spacing\s*\|\s*[0-9]+\.[0-9]+\s*±\s*[0-9]+\.[0-9]+\s*\|\s*"
        r"\*\*([0-9]+\.[0-9]+)\*\*\s*\(GUE,\s*computed\)",
        текст,
        flags=re.MULTILINE,
    )
    if строка is None:
        raise AssertionError("табличная строка p95 в сводке не найдена")
    return float(строка.group(1)), точный_p95


def _прочитать_csv() -> list[float]:
    with CSV.open(encoding="utf-8", newline="") as файл:
        строки = list(csv.DictReader(файл))
    if len(строки) != 10:
        raise AssertionError("CSV не предъявляет десять высотных строк")
    значения = [float(строка["GUE_p95"]) for строка in строки]
    if not значения:
        raise AssertionError("CSV не предъявляет эталон p95")
    return значения


def _наблюдаемое() -> dict:
    табличный_p95, точный_p95 = _прочитать_сводку()
    значения_csv = _прочитать_csv()
    уникальные_csv = sorted(set(значения_csv))
    csv_согласован = len(уникальные_csv) == 1 and (
        abs(уникальные_csv[0] - табличный_p95) <= 1e-12
    )
    разность = точный_p95 - табличный_p95
    относительное_отклонение = 100.0 * разность / табличный_p95
    return {
        "табличный_p95": табличный_p95,
        "точный_p95_поправки": точный_p95,
        "уникальные_GUE_p95_в_CSV": уникальные_csv,
        "строк_CSV": len(значения_csv),
        "разность": разность,
        "относительное_отклонение_проценты": относительное_отклонение,
        "таблица_и_CSV_согласованы": csv_согласован,
        "эталоны_согласованы": abs(разность) <= 1e-12,
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["эталоны_согласованы"] = True
    результат["разность"] = 0.0
    результат["относительное_отклонение_проценты"] = 0.0
    return результат


def _контроль() -> float:
    """Положительный контроль формы: все десять строк имеют один эталон."""
    значения = _прочитать_csv()
    return float(len(значения) == 10 and len(set(значения)) == 1)


НАБЛЮДЕНИЕ = _наблюдаемое()
assert НАБЛЮДЕНИЕ["таблица_и_CSV_согласованы"]
assert НАБЛЮДЕНИЕ["строк_CSV"] == 10
assert НАБЛЮДЕНИЕ["уникальные_GUE_p95_в_CSV"] == [1.7518]
assert НАБЛЮДЕНИЕ["точный_p95_поправки"] == 1.757099
assert not НАБЛЮДЕНИЕ["эталоны_согласованы"]
assert abs(НАБЛЮДЕНИЕ["разность"] - 0.005299) < 1e-12
assert _контроль() == 1.0
assert _ложное_наблюдаемое()["эталоны_согласованы"]


