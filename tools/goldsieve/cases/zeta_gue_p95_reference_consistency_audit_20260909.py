"""Машинный вопрос о согласованности эталона p95 для GUE.

Кейс независимо читает две записи корпуса: табличную величину 1,7518,
которую используют CSV и сводка, и позднюю запись точного закона с
величиной 1,757099. Различие между ними является диагностикой выбора
эталона, а не измерением отклонения zeta в сигмах: неопределённости
эталонов в корпусе не предъявлены. Поэтому научный статус остаётся
not-evaluated, а каскад выносит машинный ВОПРОС.
"""

from __future__ import annotations

