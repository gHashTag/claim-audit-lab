# -*- coding: utf-8 -*-
"""Машинный вопрос о невозможности выразить отклонение zeta в сигмах.

Текст корпуса печатает наблюдаемое стандартное отклонение и точное значение
GUE, но не предъявляет неопределённость ни наблюдаемого, ни эталона. Поэтому
процентное расхождение можно пересказать, а отклонение в сигмах вычислить
нельзя. Кейс читает настоящий вход и возвращает ВОПРОС с измеренной причиной,
не превращая отсутствие погрешности в подтверждение закона GUE.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from goldsieve.sieve import Claim


if __name__ in sys.modules:
    raise RuntimeError(
        "кейс должен загружаться через module_from_spec без регистрации"
    )


КОРЕНЬ = Path(__file__).resolve().parent.parent
ИСТОЧНИК = (
    КОРЕНЬ.parent
    / "corpus"
    / "trinity"
    / "data"
    / "zeta"
    / "zeta_gue_analysis_results.md"
)
КОД_ВОПРОСА = "reference_uncertainty_absent"


def _текст() -> str:
    return ИСТОЧНИК.read_text(encoding="utf-8")


def _наблюдаемое() -> dict:
    текст = _текст()
    строка = re.search(
        r"\|\s*Std deviation\s*\|\s*([0-9]+\.[0-9]+)\s*\|"
        r"\s*([0-9]+\.[0-9]+)\s*\|",
        текст,
    )
    точный = re.search(
        r"std\s+([0-9]+\.[0-9]+),\s+p50\s+",
        текст,
    )
    if строка is None or точный is None:
        raise AssertionError("строки наблюдаемого и точного GUE не найдены")

    наблюдаемое = float(строка.group(1))
    приближение = float(строка.group(2))
    точный_gue = float(точный.group(1))
    # В тексте нет ни ±-поля для std, ни отдельной погрешности точного
    # эталона. Процентное расхождение вычисляется только как описательная
    # величина и не подменяет отклонение в сигмах.
    имеет_погрешность_наблюдения = bool(
        re.search(r"Std deviation[^|\n]*[±+\-]\s*[0-9]", текст)
    )
    имеет_погрешность_эталона = bool(
        re.search(
            r"(?im)^.*(?:exact\s+GUE|точн\w*).*?"
            r"(?:±|uncertainty|погрешност\w*).*$",
            текст,
        )
    )
    return {
        "наблюдаемое_std": наблюдаемое,
        "эталон_wigner": приближение,
        "эталон_exact_gue": точный_gue,
        "разность_с_exact_gue": наблюдаемое - точный_gue,
        "процентное_расхождение": 100.0 * (наблюдаемое - точный_gue) / точный_gue,
        "погрешность_наблюдаемого_предъявлена": имеет_погрешность_наблюдения,
        "погрешность_эталона_предъявлена": имеет_погрешность_эталона,
        "отклонение_в_сигмах_вычислимо": (
            имеет_погрешность_наблюдения and имеет_погрешность_эталона
        ),
        "статус_входа": "verified-in-scope",
        "научный_статус": "not-evaluated",
        "код_вопроса": КОД_ВОПРОСА,
    }


def _ложное_наблюдаемое() -> dict:
    результат = _наблюдаемое()
    результат["погрешность_наблюдаемого_предъявлена"] = True
    результат["погрешность_эталона_предъявлена"] = True
    результат["отклонение_в_сигмах_вычислимо"] = True
    результат["код_вопроса"] = ""
    return результат


def _контроль() -> float:
    результат = _наблюдаемое()
    return float(
        результат["эталон_exact_gue"] > 0.0
        and результат["эталон_wigner"] > 0.0
    )


Наблюдение = _наблюдаемое()
assert Наблюдение["наблюдаемое_std"] == 0.4009
assert Наблюдение["эталон_exact_gue"] == 0.424258
assert not Наблюдение["погрешность_наблюдаемого_предъявлена"]
assert not Наблюдение["погрешность_эталона_предъявлена"]
assert not Наблюдение["отклонение_в_сигмах_вычислимо"]
assert _контроль() == 1.0
assert _ложное_наблюдаемое()["отклонение_в_сигмах_вычислимо"]


