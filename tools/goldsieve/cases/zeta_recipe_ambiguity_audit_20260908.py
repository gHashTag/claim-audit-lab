"""Машинный вопрос об однозначности рецепта наблюдаемого zeta.

Наблюдаемое читается из файла корпуса, а перечень вариантов — из отдельного
паспорта воспроизводимости. Эталон однозначного рецепта намеренно не объявлен:
несколько предъявленных вариантов попадают в ту же печатную полосу. Кейс не
превращает это молчание в подтверждение; сито обязано вернуть ВОПРОС с кодом
причины.
"""

from __future__ import annotations

import json
import os
import re

from goldsieve.sieve import Claim

КОРПУС = os.environ.get(
    "TRINITY_ZETA_ANALYSIS",
    "/home/user/workspace/corpus/trinity/data/zeta/zeta_gue_analysis_results.md",
)
ПАСПОРТ = os.environ.get(
    "TRINITY_ZETA_PASSPORT",
    "/home/user/workspace/goldsieve/tick337-zeta-passport.txt",
)
ОЖИДАЕМЫЕ_ВАРИАНТЫ = 14
ОЖИДАЕМЫЕ_ПОПАДАНИЯ = 11


def _наблюдаемое() -> float:
    """Прочитать значение из таблицы корпуса, не пересчитывая его."""
    with open(КОРПУС, encoding="utf-8") as файл:
        for строка in файл:
            клетки = [часть.strip() for часть in строка.strip().strip("|").split("|")]
            if len(клетки) >= 2 and клетки[0] == "Std deviation":
                число = re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)", клетки[1])
                if число:
                    return float(число.group(1))
    raise AssertionError("строка Std deviation в корпусе не найдена")


def _паспорт() -> dict:
    """Загрузить отдельный паспорт вариантов через обычный JSON-разбор."""
    with open(ПАСПОРТ, encoding="utf-8") as файл:
        паспорт = json.load(файл)
    варианты = паспорт.get("варианты_рецепта")
    попадания = паспорт.get("воспроизводят_0_4009")
    if not isinstance(варианты, dict) or not isinstance(попадания, dict):
        raise AssertionError("паспорт не предъявляет варианты и попадания")
    if not варианты or not попадания:
        raise AssertionError("паспорт не предъявляет непустые варианты")
    if not set(попадания).issubset(варианты):
        raise AssertionError("попадание отсутствует среди предъявленных вариантов")
    return {"варианты": варианты, "попадания": попадания}


def _контроль() -> float:
    """Положительный контроль: число вариантов должно быть конечным."""
    данные = _паспорт()
    return float(len(данные["варианты"]))


def _неверный_ответ() -> float:
    """Отдельная подставка, не являющаяся рецептом наблюдения."""
    return _наблюдаемое() + 1.0


def _инвентарь() -> dict:
    данные = _паспорт()
    варианты = данные["варианты"]
    попадания = данные["попадания"]
    числовые = [
        имя for имя, описание in варианты.items()
        if isinstance(описание, dict)
        and isinstance(описание.get("std"), (int, float))
        and not isinstance(описание.get("std"), bool)
    ]
    return {
        "вариантов": len(варианты),
        "числовых_вариантов": len(числовые),
        "воспроизводящих": len(попадания),
        "имена_воспроизводящих": sorted(попадания),
    }


